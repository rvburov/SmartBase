namespace SmartBase.Core.Models;

/// <summary>
/// Название записи для ПОКАЗА — всегда одна строка.
///
/// В <c>db_records.Title</c> лежит что угодно: пользователь вставляет в ячейку «Название»
/// (или в заголовок панели записи) текст с переводами строк, столько же приезжает импортом.
/// Хранить это можно и нужно как есть, а вот показывать — нет: карточка задачи, строка
/// «Расписания», лента «Журнала», плашка в сетке дня и попап года рисуют название одним
/// блоком, и многострочный текст либо растягивает строку, либо наезжает сам на себя
/// (плашка события высотой в час, поле фиксированной высоты).
///
/// Поэтому все <c>DisplayTitle</c> отдают ПЕРВУЮ НЕПУСТУЮ строку. Исключения, где текст
/// остается полным, — по одной причине у каждого:
/// <list type="bullet">
///   <item>таблица конструктора — у нее свои правила показа ячейки;</item>
///   <item>поля ввода (окна записи и задачи, заголовок панели, редактор ячейки) — там текст
///         не только показывается, но и сохраняется обратно;</item>
///   <item>поиск, сортировка и экспорт — работают по полному значению.</item>
/// </list>
/// </summary>
public static class TitleText
{
    /// <summary>
    /// Название записи, у которой его нет. В базе пустое название хранится этим текстом, а поля
    /// ввода показывают его серой подсказкой: печатать можно сразу, стирать нечего.
    /// </summary>
    public const string Placeholder = "Без названия";

    /// <summary>
    /// Названия нет: пусто, одни пробелы или «Без названия». Пустое встречается у записей, которые
    /// сохранили до правила «пустое хранится как «Без названия»», и у записей из обмена с другими
    /// программами — выглядят они так же.
    /// </summary>
    public static bool IsPlaceholder(string? title) =>
        string.IsNullOrWhiteSpace(title) || title == Placeholder;

    /// <summary>Название для поля ввода: у записи без названия поле пустое, подсказку рисует само поле.</summary>
    public static string Editable(string? title) => IsPlaceholder(title) ? "" : title!;

    /// <summary>
    /// Название, набранное в поле ввода, — в вид хранения: пустое и одни пробелы становятся
    /// «Без названия», остальное не меняется (пробелы по краям обрезает вызывающий, если нужно).
    /// </summary>
    public static string Stored(string? text) => string.IsNullOrWhiteSpace(text) ? Placeholder : text;

    /// <summary>
    /// Первая непустая строка текста (без крайних пробелов). Пустой текст и текст из одних
    /// переводов строк дают "" — вызывающий подставляет свое «Без названия».
    /// </summary>
    public static string FirstLine(string? text)
    {
        // Пусто и «одни пробелы» — одно и то же: вызывающий покажет «Без названия».
        if (string.IsNullOrWhiteSpace(text)) return "";
        // Однострочное название (подавляющее большинство) отдаем как есть: ни разбора,
        // ни аллокаций, ни неожиданного Trim у текста, который пользователь набрал сам.
        if (text.AsSpan().IndexOfAny('\n', '\r') < 0) return text;

        // Разбираем по обоим символам: CRLF даст пустой сегмент (он пропустится), а
        // одинокий CR — тоже перенос строки (вставка из старых редакторов и с Mac).
        foreach (var line in text.Split('\n', '\r'))
        {
            var trimmed = line.Trim();
            if (trimmed.Length > 0) return trimmed;
        }
        return "";
    }
}
