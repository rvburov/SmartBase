namespace SmartBase.Core.Documents;

/// <summary>
/// Единая очередь вызовов PDFium на весь процесс.
///
/// <b>Зачем.</b> <c>DocLib.Instance</c> — синглтон PDFium, и он НЕ потокобезопасен. Пока
/// рисовать страницы умели только миниатюры, хватало их собственного замка. Теперь в программе
/// три места, которые зовут PDFium из разных потоков: миниатюры ленты, панель чтения (страницы
/// рисуются по мере прокрутки) и расширение «Водяной знак» (впечатывает знак в пиксели). Два
/// независимых замка не спасают вовсе — они пропускают друг друга, и это ровно тот случай,
/// когда падение приходит из недр нативной библиотеки без единой понятной строки в журнале.
///
/// <b>Правило одно: ЛЮБОЙ вызов в PDFium идет через этот замок.</b> Держать между вызовами
/// открытый документ можно — PDFium это позволяет, пока сами вызовы не идут одновременно.
/// Поэтому замок берется на короткие операции (открыть документ, отрисовать страницу), а не на
/// весь прогон: иначе расширение, штампующее сотню страниц, заморозило бы ленту библиотеки на
/// все время работы.
/// </summary>
public static class PdfGate
{
    private static readonly object Lock = new();

    /// <summary>Выполнить работу с PDFium, дождавшись своей очереди.</summary>
    public static T Run<T>(Func<T> work)
    {
        lock (Lock) return work();
    }

    /// <summary>То же для работы без результата.</summary>
    public static void Run(Action work)
    {
        lock (Lock) work();
    }
}
