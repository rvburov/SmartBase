using SmartBase.Core.Models;

namespace SmartBase.Notifications;

/// <summary>
/// Источник событий задач для службы уведомлений. Три операции связаны общим состоянием
/// (курсоры прочитанного по каждой базе), поэтому это интерфейс, а не набор делегатов:
/// служба подменяет его целиком в тестах.
/// </summary>
public interface ITaskEventSource
{
    /// <summary>Новые события по всем допущенным базам. Зовется из ФОНОВОГО потока:
    /// читает свои подключения и не трогает общие контексты. Курсоры при этом только
    /// намечаются — фиксирует их <see cref="Commit"/>.</summary>
    IReadOnlyList<TaskEvent> Read();

    /// <summary>Зафиксировать намеченные курсоры (UI-поток: единственный, кто пишет app.db).
    /// Служба зовет его после показа плашек прохода — так курсор перешагивает и чужие
    /// события, которые иначе перечитывались бы каждым тиком.</summary>
    void Commit();

    /// <summary>Сдвинуть курсоры на текущий хвост очередей, ничего не показывая: включили
    /// тумблер — историю накопленного не вываливаем.</summary>
    void Reseed();
}
