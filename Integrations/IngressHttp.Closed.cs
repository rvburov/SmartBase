namespace SmartBase.Integrations;

/// <summary>
/// Слушающий слой сборки без приема по сети — заглушка вместо слушателя.
///
/// Этот файл компилируется ТОЛЬКО при <c>-p:NoListener=true</c>, и вместо него в обычной сборке
/// берется <c>IngressHttp.Open.cs</c> (подмена — в SmartBase.csproj). Прием на <c>127.0.0.1</c>
/// данные наружу не отдает, и убирать его незачем — но открытый порт на секретной машине вызовет
/// вопросы, и ответ «его физически нет» проверяется за минуту, а «он есть, но безопасен» —
/// никогда (docs/ROADMAP-API.md, 10.16.1).
///
/// Массовый канал в закрытом контуре все равно папка обмена (раздел 6.6), поэтому потеря здесь
/// невелика: остаются папка-приемник и канал командной строки, которым порт не нужен.
///
/// Подмена сделана файлом, а не <c>#if</c>, по той же причине, что и у отправляющего слоя:
/// условная компиляция живет ровно в одном месте — в двери (<c>IngressGate.ListenerBuild</c>), —
/// иначе две сборки начнут расходиться поведением в местах, о которых никто не помнит.
/// </summary>
public sealed class IngressHttp : IDisposable
{
    private IngressHttp() { }

    /// <summary>
    /// Открыть порт нечем: слушающего кода в этой сборке нет. Отказ идет тем же путем, что и
    /// занятый порт, — вызывающему не приходится знать, какая перед ним сборка.
    /// </summary>
    public static IngressHttp? TryOpen(string prefix, Func<IngressCall, IngressAnswer> answer,
                                       out string trouble)
    {
        _ = prefix; _ = answer;

        trouble = "сборка без слушателя: принимать обращения по сети она не умеет";
        return null;
    }

    /// <summary>Закрывать нечего — объект в этой сборке не создается вовсе.</summary>
    public void Dispose() { }
}
