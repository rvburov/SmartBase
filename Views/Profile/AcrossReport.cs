using SmartBase.Core.Models;

namespace SmartBase.Views.Profile;

/// <summary>
/// Итог массовой правки области «все базы данных» (docs/ROADMAP-API.md, шаг 15).
///
/// <b>Показывается только когда какая-то база правку не приняла</b> — окном. Над таблицей
/// пояснений нет: нормальный исход видно по самой галке, а строка «куда уйдут правки» мешала
/// читать таблицу. Молчать же о базе, которая правку не приняла, нельзя — разнобой прав остался
/// бы незамеченным.
///
/// <b>Почему это отдельный класс, а не строка внутри панели.</b> Фраза должна быть одинаково
/// честной при любом наборе баз, а проверить это на живом окне нельзя, на чистой функции —
/// можно, и проверено (Tests/Unit/AcrossReportTests.cs).
///
/// Правило одно: <b>называть базы по имени</b>. «Не затронуто 2 базы» человеку нечего делать с
/// этим числом; «Склад — вас понизили» он может поправить и повторить.
/// </summary>
public static class AcrossReport
{
    /// <summary>
    /// Что вышло из массовой правки.
    ///
    /// Названы все три исхода, и порознь. «Не записалось» — поломка, о которой надо знать
    /// немедленно; «пропущено» — норма (администратору право не нужно, ожидающему допуска его
    /// некуда класть). Свалить их в одно «не везде получилось» значило бы пугать нормой и прятать
    /// поломку.
    /// </summary>
    public static string Outcome(PermAction action, bool allowed,
                                 IReadOnlyList<string> done,
                                 IReadOnlyList<string> failed,
                                 IReadOnlyList<string> skipped)
    {
        var what = $"«{PermActionLabels.Title(action)}» " + (allowed ? "разрешено" : "запрещено");

        var text = done.Count > 0
            ? $"{what} в базах: {string.Join(", ", done)}."
            : $"{what} — ни одной базы не затронуто.";

        if (failed.Count > 0)  text += " Не записалось: " + string.Join("; ", failed) + ".";
        if (skipped.Count > 0) text += " Пропущено: "     + string.Join("; ", skipped) + ".";

        return text;
    }
}
