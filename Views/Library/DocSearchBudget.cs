namespace SmartBase.Views.Library;

/// <summary>
/// Потолок выдачи поиска — один на раздел, а не на базу.
///
/// Поиск не листается (см. заголовок <c>ConstructorRepository.DocsPaging.cs</c>), поэтому выдача
/// обрезается потолком, и раздел обязан честно сказать, обрезана ли она. Раньше потолок уходил в
/// каждую базу отдельно — на трех базах в ленту попадало до полутора тысяч карточек, — а признак
/// обрезки считался по общему числу показанного: три базы по двести настоящих находок давали
/// «показаны первые 600» там, где ничего не обрезано, а база, вернувшая ровно потолок, из
/// которого фильтр типов отсеял половину, — молчание там, где обрезано.
///
/// Здесь остаток потолка идет по источникам по очереди, и каждый спрашивается на ОДНУ строку
/// больше остатка: лишняя строка и есть признак «там есть еще». Так «обрезано» — не догадка по
/// круглому числу, а факт: ровно потолок находок — не обрезка, потолок плюс одна — обрезка.
/// </summary>
public sealed class DocSearchBudget
{
    public DocSearchBudget(int limit) => Limit = Math.Max(1, limit);

    /// <summary>Сколько карточек раздел показывает самое большее.</summary>
    public int Limit { get; }

    /// <summary>Сколько уже принято к показу.</summary>
    public int Shown { get; private set; }

    /// <summary>Выдача обрезана: где-то остался хвост, которого человек не видит.</summary>
    public bool Capped { get; private set; }

    /// <summary>
    /// Сколько строк просить у следующего источника: остаток плюс одна на признак хвоста.
    /// 0 — потолок исчерпан, спрашивать незачем.
    /// </summary>
    public int Ask => Shown < Limit ? Limit - Shown + 1 : 0;

    /// <summary>
    /// Учесть ответ источника и сказать, сколько строк из него показывать. Вернул больше
    /// остатка — выдача обрезана, лишнее отбрасывается.
    /// </summary>
    public int Accept(int returned)
    {
        var room = Limit - Shown;
        var take = Math.Clamp(returned, 0, room);
        if (returned > room) Capped = true;
        Shown += take;
        return take;
    }

    /// <summary>
    /// Источник обрезал выдачу сам — кеш текста отдал больше потолка находок по содержимому.
    /// Показанного это не меняет, но хвост есть, и подвал обязан о нем сказать.
    /// </summary>
    public void MarkCapped() => Capped = true;
}
