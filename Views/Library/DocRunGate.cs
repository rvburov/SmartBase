namespace SmartBase.Views.Library;

/// <summary>
/// Ворота фоновой работы, у которой имеет смысл только ПОСЛЕДНИЙ результат: не больше одного
/// прогона разом, а просьбы, пришедшие во время прогона, сливаются в один повтор после него.
///
/// Так устроена перепись кеша в разделе «Библиотека документов». Каждое касание галочки
/// перезапускает ленту, а с ней и перепись, которая идет на диск за каждым файлом. Пять касаний
/// подряд давали пять обходов диска разом, и нужен был из них только последний — остальные
/// лишь отнимали у него диск и сеть. Теперь пять касаний дают два обхода: идущий и один повтор.
///
/// Итог прогона, во время которого попросили новый, устарел — показывать его нельзя, он про
/// прежний набор документов (<see cref="Stale"/>).
///
/// Чистая логика без Avalonia и без потоков: вызывается из UI-потока, и порядок вызовов там
/// задан сам собой. Закрыта тестами <c>DocRunGateTests</c>.
/// </summary>
public sealed class DocRunGate
{
    private bool _running;
    private bool _again;

    /// <summary>Идет ли прогон.</summary>
    public bool Running => _running;

    /// <summary>
    /// Попросить прогон. true — ворота были свободны, начинать сейчас. false — прогон уже
    /// идет; просьба запомнена, и по его окончании <see cref="Done"/> велит повторить.
    /// </summary>
    public bool Request()
    {
        if (_running)
        {
            _again = true;
            return false;
        }
        _running = true;
        return true;
    }

    /// <summary>Во время прогона попросили новый — итог идущего устарел.</summary>
    public bool Stale => _again;

    /// <summary>
    /// Прогон кончился. true — пока он шел, просили еще раз: повторить (ворота остаются
    /// занятыми). false — ворота свободны.
    /// </summary>
    public bool Done()
    {
        if (_again)
        {
            _again = false;
            return true;
        }
        _running = false;
        return false;
    }
}
