using SmartBase.Core.Documents;
using SmartBase.Database.DocIndex;

namespace SmartBase.Views.Settings;

/// <summary>
/// Сводка кеша документов на экране «Настройки → Библиотека документов» — чистая логика без
/// Avalonia, поэтому проверяется тестами.
///
/// Исходы разбора названы порознь и теми же словами, что чипы карточек: раньше чужие форматы,
/// битые файлы и файлы тяжелее порога складывались в одно «Не прочитано», хотя «не прочитан» в
/// разделе значит совсем другое — «еще не читали», — а порог, который мог бы помочь, задается в
/// соседней выпадашке. «Разобрано» стоит всегда, остальные исходы — только когда они есть:
/// «Не удалось прочитать: 0» человеку ничего не говорит (так решил пользователь).
///
/// У файлов тяжелее порога — подсказка, что их прочитает поднятый порог. Она правдива потому, что
/// перепись берет такой файл в чтение, как только порог его пропускает
/// (<c>DocTextIndex.Survey</c>).
/// </summary>
public static class LibraryCacheSummary
{
    public static string Compose(DocCacheStats stats, long thumbsBytes)
    {
        var text = $"Разобрано документов: {stats.Indexed}.";
        if (stats.NoText > 0)      text += $" Без текстового слоя: {stats.NoText}.";
        if (stats.Unsupported > 0) text += $" Формат без чтения текста: {stats.Unsupported}.";
        if (stats.Failed > 0)      text += $" Не удалось прочитать: {stats.Failed}.";
        if (stats.TooBig > 0)      text += $" Тяжелее порога: {stats.TooBig} — прочитаются, если поднять порог.";

        // Форматы перечисляем прямо здесь: без этого «разобрано 1 190» не объясняет, почему часть
        // документов так и не находится по содержимому, а это главный источник недоумения.
        return text +
               $" Занято на диске: {Mb(stats.Bytes + thumbsBytes)}." +
               $" Текст читается у {DocTextExtractor.SupportedText}; распознавания картинок нет, " +
               "поэтому сканы без текстового слоя в поиск по содержимому не попадают. " +
               "Очистка удаляет только кеш — сами документы и записи не трогаются, " +
               "а прочитать их заново можно кнопкой в разделе.";
    }

    /// <summary>«840 КБ», «12,5 МБ» — размер кеша на экране настроек.</summary>
    private static string Mb(long bytes) =>
        bytes < 1024L * 1024 ? $"{Math.Max(1, bytes / 1024)} КБ"
                             : $"{bytes / (1024.0 * 1024):0.#} МБ";
}
