namespace SmartBase.Utils;

/// <summary>
/// Размер в байтах словами: «812 КБ», «3,4 МБ», «1,21 ГБ».
///
/// <b>Почему отдельно.</b> Одно и то же выражение — три ветки с одинаковыми порогами и
/// разрядностью — жило в ПЯТИ местах: паспорт интеграций, строки настроек, шапка главного окна,
/// строка базы данных и «Диагностика». Пороги совпадали не потому, что их согласовали, а потому
/// что каждую следующую копию писали с предыдущей; поправь одну — и «3,4 МБ» в одном экране
/// стало бы «3,40 МБ» в соседнем.
///
/// Разрядность растет вместе с единицей и намеренно: килобайты читают как целое («812 КБ»),
/// гигабайты — с сотыми («1,21 ГБ»), потому что разница в сотню мегабайт между «1 ГБ» и «1 ГБ»
/// не видна вовсе. Разделитель дробной части — из текущей культуры, как везде в интерфейсе.
///
/// Ноль — это «0 КБ», а не «0 Б»: единица измерения в интерфейсе одна на всю колонку, и байты
/// среди килобайт читаются как опечатка.
/// </summary>
public static class Sizes
{
    /// <summary>
    /// Размер словами.
    /// </summary>
    /// <param name="bytes">Сколько байт.</param>
    /// <param name="tiny">Показывать ли байты у мелочи. В интерфейсе — нет: единица измерения
    /// одна на всю колонку, и «812 Б» среди килобайт читается как опечатка. В «Диагностике» —
    /// да: там разбирают, сколько на самом деле ушло, и «0 КБ» вместо «96 Б» скрывает ответ.
    /// Это ЕДИНСТВЕННОЕ различие между пятью прежними копиями, и теперь оно названо.</param>
    public static string Text(long bytes, bool tiny = false) => bytes switch
    {
        < 1024 when tiny      => $"{bytes} Б",
        < 1024L * 1024        => $"{bytes / 1024.0:N0} КБ",
        < 1024L * 1024 * 1024 => $"{bytes / 1024.0 / 1024:N1} МБ",
        _                     => $"{bytes / 1024.0 / 1024 / 1024:N2} ГБ",
    };

    /// <summary>
    /// Перечень через запятую; пустой список — «не заданы».
    ///
    /// Тоже был написан дважды — у контура безопасности и у паспорта интеграций, — а говорят они
    /// об ОДНИХ И ТЕХ ЖЕ списках политики: разрешенные адреса, папки, источники. Два разных
    /// ответа на «список пуст» в двух документах об одном и том же — не мелочь: по паспорту
    /// сверяют то, что видно на экране.
    /// </summary>
    public static string List(IReadOnlyList<string> values) =>
        values.Count == 0 ? "не заданы" : string.Join(", ", values);
}
