namespace SmartBase.Controls.Components;

/// <summary>
/// Одно действие, показанное там, где лежат данные: пункт «Действия» в контекстном меню таблицы
/// и сайдбара, кнопка в шапке открытой записи (docs/ROADMAP-API.md, шаг 6).
///
/// Живет в общих элементах, а не рядом с тем, кто его собирает: показывают его таблица, сайдбар
/// и панель записи, и ни один из них не должен знать, откуда пункт взялся — из обмена или (по
/// плану раздела 4) из расширения. Собирает список раздел данных
/// (<c>Views/ConstructorDb/IntegrationActions.cs</c>).
/// </summary>
/// <param name="Title">Как называется в меню.</param>
/// <param name="Run">Что сделать. Список записей — выделенные строки; пустой — вся коллекция.</param>
public sealed record DataAction(string Title, Func<IReadOnlyList<int>, Task> Run);
