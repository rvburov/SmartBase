namespace SmartBase.Tests.Extensions.PdfRename;

/// <summary>
/// Приемник прогресса, вызывающий обработчик ПРЯМО в потоке отправителя.
///
/// Штатный <see cref="Progress{T}"/> для тестов не годится: он публикует колбэк в контекст
/// синхронизации (в тест-хосте — пул потоков), поэтому к возврату из метода часть отчетов
/// может быть еще не доставлена, а отмена «по первому отчету» срабатывает с опозданием
/// на несколько шагов. Здесь доставка синхронная — проверки становятся детерминированными.
/// </summary>
internal sealed class SyncProgress<T>(Action<T> onReport) : IProgress<T>
{
    public void Report(T value) => onReport(value);
}
