namespace SmartBase.Tests.Extensions.Shared;

/// <summary>
/// Приемник прогресса, вызывающий обработчик ПРЯМО в потоке отправителя.
///
/// Штатный <see cref="Progress{T}"/> для тестов не годится: он публикует колбэк в контекст
/// синхронизации (в тест-хосте — пул потоков), поэтому к возврату из метода часть отчетов может
/// быть еще не доставлена, а отмена «по первому отчету» срабатывает с опозданием на несколько
/// шагов. Здесь доставка синхронная — проверки становятся детерминированными.
///
/// В самих расширениях такой же приемник встречается и в рабочем коде (например
/// <c>TimeCollectionWriter</c>) — там по той же причине: отчеты о заливке иначе приходили бы
/// в UI пачкой после ее конца, и полоса стояла бы всю запись.
/// </summary>
public sealed class SyncProgress<T>(Action<T> onReport) : IProgress<T>
{
    public void Report(T value) => onReport(value);
}
