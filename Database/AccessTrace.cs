using SmartBase.Utils;

namespace SmartBase.Database;

/// <summary>
/// След управления доступом в журнале безопасности: решения администратора о том, кого пускать
/// в базу, и попытки войти в нее по паролю.
///
/// <b>Зачем дублировать то, что и так в «Истории изменений».</b> Решения о доступе уходят в
/// change_log и сейчас — по ним соседние машины снимают и возвращают замок без перезапуска. Но
/// история живет по сроку хранения (администратор сам выбирает срок и может очистить ее одной
/// кнопкой) и ничем не защищена от правки файла. Вопрос «кто выдал себе права» задают ровно
/// тогда, когда ответ кому-то невыгоден, — и отвечать на него должен журнал, который нельзя ни
/// почистить, ни переписать незаметно. Поэтому решения лежат в обоих местах, и каждое из них
/// делает свою работу: история — транспорт, журнал — свидетельство.
///
/// <b>Чего здесь нет.</b> Галок отдельных прав: за один сеанс настройки их щелкают десятками, и
/// журнал из них состоял бы целиком. Повысить себя галкой нельзя — своя строка в таблице не
/// редактируется вовсе, а роль и допуск, которыми это делается, сюда пишутся.
///
/// <b>Почему запись не отменяет действие.</b> Правило «не записалось — не отправляем»
/// (<see cref="ExportTrace"/>, <see cref="CopyTrace"/>) про вынос данных наружу: там отказ
/// оставляет все как было. Здесь отказ запер бы администрирование базы из-за недоступного файла
/// журнала — а человек, которому нужно отозвать допуск, обычно спешит именно потому, что что-то
/// уже случилось. Строка пишется по возможности; в истории изменений она есть всегда.
/// </summary>
public static class AccessTrace
{
    /// <summary>
    /// Решение о доступе: кого оно касается и что именно сделано.
    /// </summary>
    /// <param name="dbId">База, о доступе к которой решали; 0 — база вне реестра.</param>
    /// <param name="subject">Кого касается: имя пользователя или сама база, если решение о ней.</param>
    /// <param name="explanation">Что сделано, словами: «допуск выдан», «роль: Администратор».</param>
    /// <param name="now">Момент. Передается явно — журнал проверяется тестами построчно.</param>
    public static void Decision(int dbId, string subject, string explanation, DateTimeOffset now) =>
        SecurityJournal.Add(SecurityEntry.New(
            SecurityEvent.Access,
            allowed:     true,
            who:         CurrentUser.DisplayName,
            scenario:    "",
            address:     subject,
            fields:      "",
            rows:        0,
            bytes:       0,
            bodyHash:    "",
            explanation: explanation,
            dbId:        dbId,
            at:          now));

    /// <summary>
    /// Попытка войти в базу по паролю. Верная попытка — тоже событие: она говорит, что человек
    /// получил доступ сам, без администратора.
    /// </summary>
    /// <param name="dbId">База, в которую входили.</param>
    /// <param name="ok">Пароль подошел.</param>
    /// <param name="explanation">Подробность: «пароль верный» или «неверный пароль, промах N подряд».</param>
    /// <param name="now">Момент.</param>
    public static void Signin(int dbId, bool ok, string explanation, DateTimeOffset now) =>
        SecurityJournal.Add(SecurityEntry.New(
            SecurityEvent.Signin,
            allowed:     ok,
            who:         CurrentUser.DisplayName,
            scenario:    "",
            address:     "пароль базы данных",
            fields:      "",
            rows:        0,
            bytes:       0,
            bodyHash:    "",
            explanation: explanation,
            dbId:        dbId,
            at:          now));
}
