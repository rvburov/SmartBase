    /// <summary>
    /// Завести чек-лист, если это первый запуск на чистой машине. Возвращает true, только
    /// когда задачи действительно созданы. Старт не срывает ни при каких обстоятельствах:
    /// отказ прав или ошибка записи — предупреждение в журнал и молчаливый выход
    /// (вводные задачи — приятное дополнение, а не условие работы программы).
    /// </summary>
    public static bool RunOnFreshInstall(DatabaseRegistry registry, DatabaseManager db)
    {
        if (!registry.IsFreshInstall || AppSettings.LoadIntroSeedDone()) return false;

        // Прав на чистой базе хватает всегда (ее первый пользователь — администратор),
        // но чек-лист правит СХЕМУ коллекции, а не только записи: спрашиваем ровно то,
        // что потратим, и уходим молча, если чего-то нет.
        var perms = db.Permissions;
        if (!perms.Can(PermAction.CreateCollection) || !perms.Can(PermAction.CreateRecord) ||
            !perms.Can(PermAction.CreateField)      || !perms.Can(PermAction.EditRecord))
            return false;

        // Отметку ставим ДО наполнения: прерванный на середине сидинг (снятие процесса,
        // ошибка записи) не должен доделываться следующим запуском — иначе пользователь
        // получит вторую половину чек-листа поверх своей работы.
        AppSettings.SaveIntroSeedDone(true);

        try
        {
            return Seed(db.Constructor, DateTime.Now);
        }
        catch (Exception ex)
        {
            Log.Warning(ex, "Не удалось завести вводный чек-лист первого запуска");
            return false;
        }
    }

    /// <summary>
    /// Наполнение как таковое: коллекция <see cref="CollectionName"/> и задачи-инструкции
    /// со сроком, исполнителем, назначившим, статусом и описанием. Возвращает false, если
    /// в базе уже есть хоть одна коллекция, — чужие данные чек-лист не трогает.
    /// <paramref name="now"/> — «сейчас», от него считаются сроки (в тестах фиксируется).
    /// </summary>
    public static bool Seed(ConstructorRepository repo, DateTime now)
    {
        if (repo.GetAllCollections().Count > 0) return false;

        var collectionId = repo.AddCollection(new DbCollection
        {
            Name     = CollectionName,
            Color    = CollectionColor,
            Position = 1000,
        }).Id!.Value;

        var me    = CurrentUser.DisplayName;
        var first = FirstSlot(now);

        for (var i = 0; i < Tasks.Length; i++)
        {
            var start = i == 0 ? first : now.Date.AddDays(i).AddHours(10);
            var task  = repo.AddTaskRecord(collectionId, Tasks[i].Title, me, me,
                                           ConstructorRepository.TaskStatusPlanned,
                                           new DateValue(start, start.AddHours(1), AllDay: false));
            repo.SetRecordDescription(task.Id!.Value, Tasks[i].Description);
        }

        return true;
    }

    // Срок первой задачи — ближайший целый час, но не раньше 10:00: программу открывают
    // и в середине дня, и чек-лист не должен встречать пользователя просроченной задачей.
    // Поздний вечер — исключение: сдвигать уже некуда, оставляем утро текущего дня.
    private static DateTime FirstSlot(DateTime now)
    {
        var morning = now.Date.AddHours(10);
        if (now < morning) return morning;

        var nextHour = now.Date.AddHours(now.Hour + 1);
        return nextHour.Hour is >= 10 and <= 21 ? nextHour : morning;
    }
