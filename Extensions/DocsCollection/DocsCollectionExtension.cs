using Avalonia.Controls;

namespace SmartBase.Extensions.DocsCollection;

/// <summary>
/// Расширение «Документы в коллекцию»: по выбранной папке создает коллекцию, где каждая запись —
/// документ (наименование, папка, формат, ссылка на файл). Запускается отдельным окном
/// (<see cref="DocsCollectionWindow"/>) в основном стиле приложения. Логика вынесена в
/// <see cref="DocsCollectionBuilder"/>; расширение самостоятельно и зависит только от
/// <see cref="IExtension"/> + публичного API работы с базами (RelationDbResolver/ConstructorRepository).
/// </summary>
public sealed class DocsCollectionExtension : IExtension
{
    public string Id   => "docs-collection";
    public string Name => "Документы в коллекцию";

    public string MarkdownDescription =>
        """
        Превращает папку с документами в коллекцию программы — по записи на файл. Дальше это
        обычная коллекция: строки фильтруются и сортируются, к ним дописываются свои столбцы,
        а документ открывается прямо из таблицы.

        ## Что делает

        Обходит выбранную папку и на каждый найденный файл заводит запись с четырьмя
        колонками:

        | Колонка | Что попадает |
        |---|---|
        | Наименование | имя файла без расширения (оно же название записи) |
        | Название папки | имя папки, в которой лежит документ (оно же описание записи) |
        | Формат файла | расширение без точки — `pdf`, `docx`, … |
        | Файл | ссылка на документ: открывается прямо из таблицы |

        ## Перед первым запуском

        Настраивать нечего: у расширения нет ни одного поля в разделе
        **Настройки → Расширения**. Нужна только папка с документами и база данных, в которой
        появится коллекция.

        Коллекцию заранее создавать не нужно — расширение заводит ее само.

        ## Как пользоваться

        1. Выберите **папку с документами**.
        2. При необходимости включите **«Рекурсивный поиск»** — тогда обойдутся и все
           вложенные папки.
        3. В поле **«Расширения файлов»** ограничьте отбор — например `pdf, docx`. Пустое
           поле означает «все файлы».
        4. Выберите **базу данных**, если их несколько, и нажмите **«Запустить»**.
        5. Ход работы виден на индикаторе; прервать прогон можно кнопкой «Остановить».

        ## Что получится

        Новая коллекция в выбранной базе. Название берется из имени выбранной папки; если
        коллекция с таким именем уже есть, к имени добавляется номер — существующие данные не
        затрагиваются и не дополняются.

        Сами документы никуда не копируются и не изменяются: в колонке «Файл» лежит
        абсолютный путь к документу на диске.

        ## Особенности

        - **Ссылка на файл — обычное свойство типа «файл»**: путь можно поменять вручную,
          как в любой коллекции. Автоматическая привязка к папке при этом не настраивается —
          она умеет одну папку и один формат, чего не хватает при рекурсивном обходе.
        - **Скрытые и системные файлы пропускаются**, а недоступная подпапка не прерывает
          обход: он идет дальше.
        - **Перемещенный или переименованный документ теряет ссылку.** В коллекции лежит
          путь, а не копия файла: переложили документ — поправьте путь в записи.
        - **Отмена и ошибка убирают коллекцию целиком.** Недособранной коллекции не остается,
          повторный прогон начинается с чистого места.
        - На папках в десятки тысяч файлов прогон занимает минуты: записи создаются по одной,
          зато с полной историей изменений.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new DocsCollectionWindow();
}
