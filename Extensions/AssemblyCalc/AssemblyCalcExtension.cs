using Avalonia.Controls;

namespace SmartBase.Extensions.AssemblyCalc;

/// <summary>
/// Расширение «Расчёт сборочных единиц в изделии»: переносит данные из исходного «Список КД и ТД»
/// в .xlsm-шаблон с раскраской по уровню. Запускается отдельным окном (<see cref="AssemblyCalcWindow"/>)
/// в основном стиле приложения. Логика вынесена в <see cref="AssemblyCalcEngine"/>; расширение
/// самостоятельно и зависит только от <see cref="IExtension"/> + контролов/стилей приложения.
/// </summary>
public sealed class AssemblyCalcExtension : IExtension
{
    public string Id   => "assembly-calc";
    public string Name => "Расчёт сборочных единиц";

    public string MarkdownDescription =>
        """
        Формирует файл «Расчёт сборочных единиц в изделии»: переносит выбранные столбцы из
        исходного «Список КД и ТД» (лист «Исходные данные») в .xlsm-шаблон.

        **Что делает**
        - Берёт строки источника с 6-й строки, пока заполнен столбец «Уровень».
        - Переносит уровень, наименование, децимальные номера КД/ТД, количество, состояния ТД и др.
        - Раскрашивает строки по уровню (0–10) и применяет стиль ГОСТ («GOST type A»,
          границы, центр, текстовый формат); макросы шаблона сохраняются.

        **Как пользоваться**
        1. Укажите исходный файл «Список КД и ТД» (.xlsx/.xlsm).
        2. Укажите файл-шаблон (.xlsm).
        3. Выберите папку для результата и нажмите «Запустить».

        > Результат сохраняется как «Расчет сборочных единиц (ГГГГ-ММ-ДД_ЧЧ-ММ).xlsm».
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new AssemblyCalcWindow();
}
