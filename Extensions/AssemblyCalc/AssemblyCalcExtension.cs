using Avalonia.Controls;

namespace SmartBase.Extensions.AssemblyCalc;

/// <summary>
/// Расширение «Расчет сборочных единиц в изделии»: переносит данные из исходного «Список КД и ТД»
/// в .xlsm-шаблон с раскраской по уровню. Запускается отдельным окном (<see cref="AssemblyCalcWindow"/>)
/// в основном стиле приложения. Логика вынесена в <see cref="AssemblyCalcEngine"/>; расширение
/// самостоятельно и зависит только от <see cref="IExtension"/> + контролов/стилей приложения.
/// </summary>
public sealed class AssemblyCalcExtension : IExtension
{
    /// <summary>Идентификатор строкой-константой — на него ссылается окно, когда читает
    /// свои настройки у оболочки.</summary>
    public const string ExtensionId = "assembly-calc";

    /// <summary>Имя настройки «файл-шаблон» (полный ключ хранения собирает оболочка).</summary>
    public const string TemplateKey = "template";

    public string Id   => ExtensionId;
    public string Name => "Расчет сборочных единиц";

    /// <summary>Путь к шаблону в коде не зашит: файл лежит на файловом сервере, буква
    /// смонтированного диска у каждой машины своя.</summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(TemplateKey, "Файл-шаблон", @"\\server\share\Шаблон расчета сборочных единиц в изделии.xlsm"),
    ];

    public string MarkdownDescription =>
        """
        Формирует файл «Расчет сборочных единиц в изделии»: переносит данные из готового
        «Списка КД и ТД» в шаблон расчета, раскладывая строки по уровням вложенности.
        Ручной перенос столбцов между двумя книгами делать не нужно.

        ## Что делает

        - Читает в исходном файле лист **«Исходные данные»** — именно по имени, а не первый
          попавшийся.
        - Берет строки начиная с **6-й** и до тех пор, пока заполнен столбец «Уровень»:
          первая пустая ячейка уровня считается концом данных.
        - Переносит уровень, наименование, децимальные номера КД и ТД, количество, состояния
          ТД и остальные столбцы карты переноса.
        - Раскрашивает строки по уровню вложенности (0–10) и применяет стиль ГОСТ («GOST
          type A», границы, выравнивание по центру, текстовый формат); макросы шаблона
          сохраняются.

        ## Перед первым запуском

        Нужен **файл-шаблон** — готовая книга `.xlsm` с макросами, куда пишется расчет.
        Расширение его не создает: шаблон лежит у предприятия, обычно в общей сетевой папке.

        Путь к шаблону — единственная настройка расширения (**Настройки → Расширения**,
        поле «Файл-шаблон»). Заполнять ее заранее не нужно: укажите шаблон кнопкой «Обзор» в
        самом окне, и путь запомнится — при следующем открытии он подставится сам. Поле в
        настройках нужно, чтобы посмотреть сохраненный путь, поправить его или очистить.

        Кнопка «Запустить» включается, только когда указаны все три пути — исходный файл,
        шаблон и папка результата.

        ## Как пользоваться

        1. Укажите **исходный файл** «Список КД и ТД» (.xlsx или .xlsm).
        2. Укажите **файл-шаблон** (.xlsm) — если он запомнен, поле уже заполнено.
        3. Выберите **папку для сохранения результата**.
        4. Нажмите **«Запустить»**. По окончании расширение предложит открыть папку с
           результатом.

        ## Что получится

        Новый файл **«Расчет сборочных единиц (ГГГГ-ММ-ДД_ЧЧ-ММ).xlsm»** в выбранной папке.
        Исходный файл и шаблон не изменяются: шаблон копируется, расчет пишется в копию.

        ## Особенности

        - **Два прогона в одну минуту дают одно имя файла**, и второй затирает первый: в
          имени стоят только часы и минуты. Если нужны оба результата, переименуйте первый
          или сохраните во вторую папку.
        - **Строки читаются до первого разрыва.** Пустая ячейка «Уровень» посреди списка
          обрывает перенос — все, что ниже, в расчет не попадет. Проверяйте, что столбец
          заполнен сплошь.
        - **Файл-шаблон заранее не проверяется.** Сетевая папка может быть временно
          недоступна: если к моменту запуска шаблона на месте нет, расширение скажет
          «Файл-шаблон не найден».
        - **Отдельной кнопки остановки нет.** Ход работы виден на индикаторе, а прервать
          прогон можно закрытием окна — на время работы кнопки выбора файлов выключены.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new AssemblyCalcWindow();
}
