using SmartBase.Database.Repositories;

namespace SmartBase.Extensions;

/// <summary>
/// Что действие делает с данными. Разница принципиальная, и по ней проходит граница
/// ответственности (docs/ROADMAP-API.md, раздел 9).
/// </summary>
public enum ExtensionActionKind
{
    /// <summary>
    /// Преобразователь формата: текст или файл → строки таблицы. В базу пишет ОБОЛОЧКА, обычным
    /// сопоставлением колонок — тем же, что и при импорте файла. Расширение отвечает только за
    /// разбор: чужой XML, нестандартный текст, свой бинарник.
    /// </summary>
    Transformer = 0,

    /// <summary>
    /// Операция: заполненная запись → результат. В базу пишет САМО расширение через
    /// <see cref="ConstructorRepository"/>. Этот вид важнее и встречается чаще: у операции есть
    /// собственные правила, которые в сопоставлении колонок не выразить, — присвоить номер по
    /// ГОСТ, проверить занятость серии, завести связанные записи.
    /// </summary>
    Operation,

    /// <summary>
    /// Автоматизация: строки пришли — строки ушли (docs/ROADMAP-API.md, шаг 13). Вид заведен
    /// третьим, потому что первые два отвечают на другие вопросы: преобразователь разбирает
    /// ТЕКСТ, операция работает с ОДНОЙ записью, а «свести выгрузку по проектам» — это вся
    /// таблица разом, и разбить ее на строки нельзя, не потеряв смысла.
    ///
    /// В базу не пишет и подключения не получает — как преобразователь. Может вместо строк
    /// вернуть ГОТОВЫЙ ФАЙЛ (<see cref="ActionResult.File"/>), и тогда класть его на диск будет
    /// оболочка: файл наружу — тот же транспорт, что и сеть, и дверь у него одна.
    /// </summary>
    Rows,
}

/// <summary>
/// Одно поле, которое действие ждет на входе. Оболочка показывает список полей там, где
/// настраивают шаг, и раскладывает по ним колонки источника — так же, как колонки ответа
/// ложатся на свойства коллекции.
/// </summary>
/// <param name="Key">Имя поля внутри действия (уникально в его пределах).</param>
/// <param name="Label">Подпись для человека.</param>
/// <param name="Required">Без него действие не выполняется.</param>
/// <param name="Watermark">Пример значения.</param>
public sealed record ExtensionActionField(
    string Key,
    string Label,
    bool   Required  = true,
    string Watermark = "");

/// <summary>
/// Куда действие пишет и когда оно выполняется. Репозиторий дает ОБОЛОЧКА, и это не мелочь:
/// шаг сценария идет в фоне, а общий контекст базы принадлежит интерфейсу — расширение,
/// открывшее подключение само, рано или поздно уронило бы EF на втором обращении.
/// </summary>
/// <param name="Repo">Куда писать. Права проверяются им же — действие идет теми же дверями,
/// что и человек. У ПРЕОБРАЗОВАТЕЛЯ пусто: он в базу не пишет, и давать ему подключение значило
/// бы спросить права на запись ради разбора текста.</param>
/// <param name="DbId">Ключ базы — для журнала.</param>
/// <param name="CollectionId">Коллекция, выбранная в шаге. Точка входа принадлежит СЦЕНАРИЮ, а
/// не расширению: одно расширение можно повесить на несколько каналов и коллекций.</param>
/// <param name="Now">Момент запуска. Приходит параметром, чтобы действие можно было проверить,
/// не подводя системные часы.</param>
/// <param name="Settings">Значения настроек расширения (<see cref="IExtension.Settings"/>) по их
/// ключам. Читает их ОБОЛОЧКА — на UI-потоке, до того как увести действие в фон: хранилище
/// настроек живет на общем контексте app.db, и чтение из фона однажды уронило бы его так же, как
/// чужое подключение к базе. <c>null</c> — настроек не передали, и действие читает их пустыми.</param>
/// <param name="Session">Общий непрозрачный ключ на срок открытия базы: одинаковый между
/// изолированными запусками сценария. Временное состояние действия может жить по этому ключу;
/// после закрытия базы на него нельзя полагаться. Null — прямой вызов без оболочки.</param>
/// <param name="Channel">Область сообщений сценария и его источника. Подтверждение из другого
/// сценария или потока не должно подтверждать ожидающую операцию.</param>
public sealed record ActionContext(
    ConstructorRepository?               Repo,
    int                                  DbId,
    int                                  CollectionId,
    DateTimeOffset                       Now,
    IReadOnlyDictionary<string, string>? Settings = null,
    object?                             Session = null,
    string                              Channel = "")
{
    /// <summary>Значение настройки расширения; не задано — пустая строка.</summary>
    public string Setting(string key) =>
        Settings is { } settings && settings.TryGetValue(key, out var value)
            ? (value ?? "").Trim()
            : "";
}

/// <summary>
/// Что пришло действию. У операции заполнены <see cref="Values"/> — одна запись; у
/// преобразователя — <see cref="Text"/> или <see cref="Bytes"/>; у автоматизации —
/// <see cref="Rows"/>, вся таблица предыдущего шага разом.
/// </summary>
/// <param name="Values">Поля записи по ключам из <see cref="IExtensionAction.Fields"/>. У
/// автоматизации сюда попадают ее настройки — те же поля, но заполненные один раз на шаг, а не
/// на строку: подставлять в них колонку нечего, строк много.</param>
/// <param name="Text">Исходный текст — для преобразователя.</param>
/// <param name="Bytes">Исходный файл — для преобразователя двоичного формата.</param>
/// <param name="Rows">Строки предыдущего шага — для автоматизации. Колонки ищутся без учета
/// регистра: имена приходят из чужой выгрузки.</param>
public sealed record ActionInput(
    IReadOnlyDictionary<string, string>                 Values,
    string                                              Text  = "",
    byte[]?                                             Bytes = null,
    IReadOnlyList<IReadOnlyDictionary<string, string>>? Rows  = null)
{
    /// <summary>Значение поля; чего нет — пустая строка. Крайние пробелы снимаются.</summary>
    public string Value(string key) =>
        Values.TryGetValue(key, out var value) ? (value ?? "").Trim() : "";

    /// <summary>Строки; у остальных видов действия пусто.</summary>
    public IReadOnlyList<IReadOnlyDictionary<string, string>> Table => Rows ?? [];
}

/// <summary>
/// Чем действие кончилось.
///
/// Неудача возвращается, а не бросается: у шага сценария нет человека рядом, и причина должна
/// доехать до квитанции и журнала СЛОВАМИ. Исключение оболочка тоже переживет, но текст в нем
/// написан для разработчика.
/// </summary>
/// <param name="Ok">Действие сделало свое дело.</param>
/// <param name="Explanation">Что случилось, человеческим языком: и удача, и отказ.</param>
/// <param name="Rows">Сколько записей затронуто или получено.</param>
/// <param name="Json">Строки таблицы одним массивом JSON — у преобразователя и у автоматизации.
/// Оболочка читает их обычным источником импорта, поэтому дальше работает существующее
/// сопоставление колонок без единой правки.</param>
/// <param name="File">Готовый файл — только у автоматизации, объявившей
/// <see cref="IExtensionAction.MakesFile"/>. Расширение его СОБИРАЕТ, но никуда не кладет: файл
/// наружу — тот же транспорт, что и сеть, и дверь у него одна. Папку проверяет политикой,
/// пишет и оставляет след в журнале безопасности ОБОЛОЧКА.</param>
/// <param name="FileName">Как назвать файл — имя с расширением и без пути («Строки.xlsx»).
/// Момент к нему добавит оболочка: выгрузка повторяется по расписанию, и вчерашний файл не
/// должен молча пропадать под сегодняшним.</param>
/// <param name="Reply">Слова действия, обращенные к ОТПРАВИТЕЛЮ, — тому, чье сообщение или
/// событие завело сценарий. Пусто — отправителю действие ничего не говорит.
///
/// Отдельно от <see cref="Explanation"/>, потому что читателей двое. Объяснение читает тот, кто
/// настраивал обмен: «коллекция не подходит под журнал» ему понятно и нужно. Отправителю оно не
/// скажет ничего — исправить это он не может; ему нужны слова о том, что зависит от него. Отказ
/// без слов отправителю оболочка понимает как сбой и отвечает тем, что на этот случай велел
/// отвечать человек.</param>
public sealed record ActionResult(
    bool    Ok,
    string  Explanation,
    int     Rows     = 0,
    string  Json     = "",
    byte[]? File     = null,
    string  FileName = "",
    string  Reply    = "")
{
    public static ActionResult Failed(string reason) => new(false, reason);

    /// <summary>
    /// Отказ, причина которого — в самом сообщении отправителя: он может исправить ее сам, и
    /// слова отказа обращены к нему.
    /// </summary>
    public static ActionResult Refused(string reply) => new(false, reply, Reply: reply);

    /// <summary>
    /// Что сказать отправителю: его слова, а при удаче без особых слов — объяснение («что
    /// сделано» отправителю и есть ответ).
    /// </summary>
    public string Answer => Reply.Length > 0 ? Reply : Ok ? Explanation : "";

    /// <summary>Операция сделана.</summary>
    public static ActionResult Done(string explanation, int rows = 1) => new(true, explanation, rows);

    /// <summary>Преобразователь разобрал вход в строки.</summary>
    public static ActionResult Table(string json, int rows) =>
        new(true, $"разобрано строк: {rows}", rows, json);

    /// <summary>Автоматизация отдает строки дальше по сценарию.</summary>
    public static ActionResult Rowset(string json, int rows, string explanation = "") =>
        new(true, explanation.Length > 0 ? explanation : $"строк: {rows}", rows, json);

    /// <summary>Автоматизация собрала файл; класть его на диск будет оболочка.</summary>
    public static ActionResult MadeFile(byte[] bytes, string name, string explanation, int rows = 0) =>
        new(true, explanation, rows, "", bytes, name);
}

/// <summary>
/// Действие расширения — то, что расширение умеет делать над данными без своего окна.
///
/// Заводится тем же приемом, что и настройки: необязательным свойством
/// <see cref="IExtension.Actions"/>. Расширение по-прежнему зависит только от
/// <see cref="IExtension"/> и ничего не знает ни о сценариях, ни о каналах — сценарий зовет его
/// шагом, а откуда пришли данные (папка обмена, ответ сторонней программы, файл руками), действие
/// не спрашивает.
///
/// <b>В сеть действие не ходит и запросов не принимает.</b> Транспорт остается у оболочки:
/// иначе белый список, политика и журнал размножились бы по числу расширений и перестали быть
/// проверяемыми. Правило сторожит сборка — <c>OneDoorOutwardTests</c> роняет тесты, если в
/// <c>Extensions/</c> встретился сетевой тип.
///
/// <b>Само действие не открывает диалог.</b> Спорная операция возвращает отказ или запрос
/// подтверждения в Reply. Ответ приходит отдельным событием, временное состояние можно
/// привязать к ActionContext.Session; молчаливая перезапись не допускается.
/// </summary>
public interface IExtensionAction
{
    /// <summary>Стабильный ключ действия внутри расширения.</summary>
    string Key { get; }

    /// <summary>Имя для человека — его видно в шаге сценария.</summary>
    string Name { get; }

    /// <summary>Что делает — одной строкой, под именем.</summary>
    string Description { get; }

    /// <summary>Вид: преобразователь формата или операция.</summary>
    ExtensionActionKind Kind { get; }

    /// <summary>
    /// Операция выбирает права по содержимому сообщения, а не всегда создает запись.
    /// Оболочка передает ей репозиторий с действующими правами: мутаторы проверяют их сами,
    /// чтение обязано проверить действие. У остальных операций остается входной CreateRecord.
    /// </summary>
    bool ChecksPermissions => false;

    /// <summary>
    /// Поля, которые действие ждет на входе. У преобразователя пусто: он получает текст или
    /// файл целиком. У автоматизации это НАСТРОЙКИ шага — имя колонки-ключа, имя листа: они
    /// заполняются один раз, а не на строку.
    /// </summary>
    IReadOnlyList<ExtensionActionField> Fields => [];

    /// <summary>
    /// Действие возвращает готовый файл (<see cref="ActionResult.File"/>), а кладет его на диск
    /// оболочка. Объявляется заранее, а не выясняется по результату: папку надо спросить при
    /// настройке шага и проверить политикой ДО запуска — «папка не разрешена» должно читаться в
    /// списке сценариев, а не в журнале наутро.
    /// </summary>
    bool MakesFile => false;

    /// <summary>
    /// Выполнить действие ОДИН раз: операция — над одной записью, преобразователь — над одним
    /// входом. Обход строк ведет оболочка: она же считает итоги и пишет журнал.
    ///
    /// Операции подключение к базе дает оболочка (<see cref="ActionContext.Repo"/>), и оно
    /// заполнено всегда; преобразователю оно не полагается вовсе. Проверить его на месте все
    /// равно стоит: отказ словами понятнее, чем разыменование пустой ссылки в фоне.
    /// </summary>
    ActionResult Run(ActionContext context, ActionInput input);
}
