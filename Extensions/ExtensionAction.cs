using SmartBase.Database.Repositories;

namespace SmartBase.Extensions;

/// <summary>
/// Что действие делает с данными. Разница принципиальная, и по ней проходит граница
/// ответственности (docs/ROADMAP-API.md, раздел 9).
/// </summary>
public enum ExtensionActionKind
{
    /// <summary>
    /// Преобразователь формата: текст или файл → строки таблицы. В базу пишет ОБОЛОЧКА, обычным
    /// сопоставлением колонок — тем же, что и при импорте файла. Расширение отвечает только за
    /// разбор: чужой XML, нестандартный текст, свой бинарник.
    /// </summary>
    Transformer = 0,

    /// <summary>
    /// Операция: заполненная запись → результат. В базу пишет САМО расширение через
    /// <see cref="ConstructorRepository"/>. Этот вид важнее и встречается чаще: у операции есть
    /// собственные правила, которые в сопоставлении колонок не выразить, — присвоить номер по
    /// ГОСТ, проверить занятость серии, завести связанные записи.
    /// </summary>
    Operation,
}

/// <summary>
/// Одно поле, которое действие ждет на входе. Оболочка показывает список полей там, где
/// настраивают шаг, и раскладывает по ним колонки источника — так же, как колонки ответа
/// ложатся на свойства коллекции.
/// </summary>
/// <param name="Key">Имя поля внутри действия (уникально в его пределах).</param>
/// <param name="Label">Подпись для человека.</param>
/// <param name="Required">Без него действие не выполняется.</param>
/// <param name="Watermark">Пример значения.</param>
public sealed record ExtensionActionField(
    string Key,
    string Label,
    bool   Required  = true,
    string Watermark = "");

/// <summary>
/// Куда действие пишет и когда оно выполняется. Репозиторий дает ОБОЛОЧКА, и это не мелочь:
/// шаг сценария идет в фоне, а общий контекст базы принадлежит интерфейсу — расширение,
/// открывшее подключение само, рано или поздно уронило бы EF на втором обращении.
/// </summary>
/// <param name="Repo">Куда писать. Права проверяются им же — действие идет теми же дверями,
/// что и человек.</param>
/// <param name="DbId">Ключ базы — для журнала.</param>
/// <param name="CollectionId">Коллекция, выбранная в шаге. Точка входа принадлежит СЦЕНАРИЮ, а
/// не расширению: одно расширение можно повесить на несколько каналов и коллекций.</param>
/// <param name="Now">Момент запуска. Приходит параметром, чтобы действие можно было проверить,
/// не подводя системные часы.</param>
public sealed record ActionContext(
    ConstructorRepository Repo,
    int                   DbId,
    int                   CollectionId,
    DateTimeOffset        Now);

/// <summary>
/// Что пришло действию. У операции заполнены <see cref="Values"/> — одна запись; у
/// преобразователя — <see cref="Text"/> или <see cref="Bytes"/>.
/// </summary>
/// <param name="Values">Поля записи по ключам из <see cref="IExtensionAction.Fields"/>.</param>
/// <param name="Text">Исходный текст — для преобразователя.</param>
/// <param name="Bytes">Исходный файл — для преобразователя двоичного формата.</param>
public sealed record ActionInput(
    IReadOnlyDictionary<string, string> Values,
    string                              Text  = "",
    byte[]?                             Bytes = null)
{
    /// <summary>Значение поля; чего нет — пустая строка. Крайние пробелы снимаются.</summary>
    public string Value(string key) =>
        Values.TryGetValue(key, out var value) ? (value ?? "").Trim() : "";
}

/// <summary>
/// Чем действие кончилось.
///
/// Неудача возвращается, а не бросается: у шага сценария нет человека рядом, и причина должна
/// доехать до квитанции и журнала СЛОВАМИ. Исключение оболочка тоже переживет, но текст в нем
/// написан для разработчика.
/// </summary>
/// <param name="Ok">Действие сделало свое дело.</param>
/// <param name="Explanation">Что случилось, человеческим языком: и удача, и отказ.</param>
/// <param name="Rows">Сколько записей затронуто или получено.</param>
/// <param name="Json">Строки таблицы одним массивом JSON — только у преобразователя. Оболочка
/// читает их обычным источником импорта, поэтому дальше работает существующее сопоставление
/// колонок без единой правки.</param>
public sealed record ActionResult(
    bool   Ok,
    string Explanation,
    int    Rows = 0,
    string Json = "")
{
    public static ActionResult Failed(string reason) => new(false, reason);

    /// <summary>Операция сделана.</summary>
    public static ActionResult Done(string explanation, int rows = 1) => new(true, explanation, rows);

    /// <summary>Преобразователь разобрал вход в строки.</summary>
    public static ActionResult Table(string json, int rows) =>
        new(true, $"разобрано строк: {rows}", rows, json);
}

/// <summary>
/// Действие расширения — то, что расширение умеет делать над данными без своего окна.
///
/// Заводится тем же приемом, что и настройки: необязательным свойством
/// <see cref="IExtension.Actions"/>. Расширение по-прежнему зависит только от
/// <see cref="IExtension"/> и ничего не знает ни о сценариях, ни о каналах — сценарий зовет его
/// шагом, а откуда пришли данные (папка обмена, ответ чужой программы, файл руками), действие
/// не спрашивает.
///
/// <b>В сеть действие не ходит и запросов не принимает.</b> Транспорт остается у оболочки:
/// иначе белый список, политика и журнал размножились бы по числу расширений и перестали быть
/// проверяемыми. Правило сторожит сборка — <c>OneDoorOutwardTests</c> роняет тесты, если в
/// <c>Extensions/</c> встретился сетевой тип.
///
/// <b>Подтверждать некому.</b> В окне расширение может спросить человека «писать поверх?»; у
/// действия собеседника нет, и спорный случай обязан кончаться отказом с объяснением, а не
/// молчаливой перезаписью.
/// </summary>
public interface IExtensionAction
{
    /// <summary>Стабильный ключ действия внутри расширения.</summary>
    string Key { get; }

    /// <summary>Имя для человека — его видно в шаге сценария.</summary>
    string Name { get; }

    /// <summary>Что делает — одной строкой, под именем.</summary>
    string Description { get; }

    /// <summary>Вид: преобразователь формата или операция.</summary>
    ExtensionActionKind Kind { get; }

    /// <summary>
    /// Поля, которые действие ждет на входе. У преобразователя пусто: он получает текст или
    /// файл целиком.
    /// </summary>
    IReadOnlyList<ExtensionActionField> Fields => [];

    /// <summary>
    /// Выполнить действие ОДИН раз: операция — над одной записью, преобразователь — над одним
    /// входом. Обход строк ведет оболочка: она же считает итоги и пишет журнал.
    /// </summary>
    ActionResult Run(ActionContext context, ActionInput input);
}
