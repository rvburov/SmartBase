    /// <summary>
    /// Разобрать строку настройки в список кодов организации: разделители — запятая, точка с
    /// запятой и перевод строки, крайние пробелы снимаются, пустые куски и повторы выбрасываются.
    /// Порядок — как ввел человек: первый код станет выбранным по умолчанию.
    /// </summary>
    public static IReadOnlyList<string> ParseOrgCodes(string? raw)
    {
        var seen  = new HashSet<string>(StringComparer.CurrentCultureIgnoreCase);
        var codes = new List<string>();

        foreach (var part in (raw ?? "").Split([',', ';', '\n', '\r'], StringSplitOptions.RemoveEmptyEntries))
        {
            var code = part.Trim();
            if (code.Length > 0 && seen.Add(code)) codes.Add(code);
        }

        return codes;
    }
