using Avalonia.Controls;

namespace SmartBase.Extensions.DocRegistry;

/// <summary>
/// Расширение «Регистрация КД»: выдает документу обозначение по ГОСТ 2.201-80
/// (<c>код организации.код ЕСКД.номер</c>) и заводит строку в журнале регистрации — готовой
/// коллекции с восемью столбцами (см. <see cref="RegistrySchema"/>). Запускается отдельным
/// окном (<see cref="DocRegistryWindow"/>) в основном стиле приложения.
///
/// Второй способ работы — загрузка готового списка номеров файлом: номера в нем уже выданы,
/// расширение их проверяет и заносит в журнал разом (<see cref="RegistryFile"/>,
/// <see cref="RegistryImport"/>).
///
/// Логика вынесена целиком из UI: <see cref="Designation"/> — обозначения и номера,
/// <see cref="EskdCatalog"/> — справочник ЕСКД, <see cref="RegistrySchema"/> — эталон
/// коллекции, <see cref="DocRegistrar"/> — сама запись. Расширение самостоятельно и зависит
/// только от <see cref="IExtension"/> + публичного API работы с базами
/// (RelationDbResolver/ConstructorRepository), как «Документы в коллекцию».
/// </summary>
public sealed class DocRegistryExtension : IExtension
{
    public const string ExtensionId = "doc-registry";

    /// <summary>Настройка: коды организации через запятую — из них собирается выпадающий список.</summary>
    public const string OrgCodesKey = "orgs";

    /// <summary>
    /// Настройка: ФИО регистратора. Объявлена настройкой, а не спрятана внутри окна, потому что
    /// у машины она одна и меняется редко — вводить ее заново на каждый документ незачем. Окно
    /// подставляет значение при открытии и записывает обратно после регистрации, поэтому
    /// поправить ФИО можно и там, и на экране настроек — это одно и то же значение.
    /// </summary>
    public const string FioKey = "fio";

    /// <summary>
    /// Настройка: база данных, в которой лежит журнал регистрации, — по ИМЕНИ из списка баз.
    /// Восстанавливается при открытии окна; имя не нашлось (базу переименовали или отключили) —
    /// берется первая база, как и раньше.
    /// </summary>
    public const string DatabaseKey = "database";

    /// <summary>
    /// Настройка: коллекция-журнал, в которую пишутся регистрации, — по ИМЕНИ внутри выбранной
    /// базы. Имя не нашлось — не выбирается НИЧЕГО: наугад взятая первая коллекция тут же
    /// отвечала бы «Вы выбрали неправильную коллекцию» на пустом месте.
    /// </summary>
    public const string CollectionKey = "collection";

    public string Id   => ExtensionId;
    public string Name => "Регистрация КД";

    public string MarkdownDescription =>
        """
        Выдает конструкторскому документу обозначение по ГОСТ 2.201-80 и заводит строку в журнале
        регистрации — коллекции программы.

        ## Обозначение

        Собирается по маске `Код организации.Код ЕСКД.Порядковый номер`, например
        `АБВГ.301121.001`. Номер — первый свободный в своей серии: счетчика расширение не хранит,
        а перед каждой записью заново читает столбец «Обозначение» коллекции и берет первый
        незанятый номер, считая с 001. Серия — пара «организация + код ЕСКД», у каждой пары своя
        нумерация 001–999.

        | В журнале по серии `АБВГ.301121.` | Новый номер |
        |---|---|
        | пусто | 001 |
        | 001, 002, 003 | 004 |
        | 001, 003 | 002 — дырки заполняются |
        | строку с 002 удалили | 002 — номер освободился |
        | только `АБВГ.723611.001` | 001 — другая серия |
        | заняты все 001–999 | отказ |

        **Занимают номер** и повторно его выдать не дают: исполнение `…001-01`, свернутые
        исполнения `…001 (01-19)`, приписки `…001 (копия)` и `…001СБ` (хвост читается до первой
        нецифры), строчные буквы в коде организации, лишние пробелы по краям.

        **Не занимают номер** — такие строки пропускаются целиком, и номер по ним уйдет второй
        раз (их в журнале надо исправлять):

        | Строка | Почему пропускается |
        |---|---|
        | `…0011` — четыре цифры | не номер по ГОСТ: занял бы номер 11 по ошибке разбора |
        | `…01` — две цифры | это и 001, и обрубок 011 или 014 — гадать нельзя |
        | `АБВГ.301121. 001` | пробел после точки: в начале хвоста нет цифр |
        | `АБВГ.301121-001` | дефис вместо точки: приставка серии не совпала |
        | латинская буква в коде организации | для программы это другая серия |
        | `…000` | номера 000 не бывает |
        | два обозначения в одной ячейке | читается только первое |

        ## Номер и исполнение

        Обозначение в окне собрано в один ряд из своих частей — код организации, код ЕСКД, номер и
        исполнение, — и читается как готовый номер: `АБВГ.301121.012-01`.

        **Номер выбирают из списка.** Как только введен код ЕСКД, список наполняется по серии:

        | В списке | Что это |
        |---|---|
        | **Новый номер** | первый свободный номер серии |
        | **Без исполнения** | выданные номера, у которых исполнений еще нет |
        | **С исполнением** | выданные номера, у которых исполнения уже есть |

        Заголовки групп выбраться не могут, а пустая группа не показывается. В самом поле стоит
        только номер, поэтому ряд по-прежнему читается как обозначение.

        Выбор номера и решает, что регистрируется:

        | Выбрано | Исполнение | Запишется |
        |---|---|---|
        | Новый номер `014` | **недоступно** | `АБВГ.301121.014` |
        | `001` (без исполнения) | `01` | `АБВГ.301121.001-01` |
        | `003` (есть `01`, `02`) | `03` | `АБВГ.301121.003-03` |

        **Исполнение не выбирают**: у выбранного номера свободно только следующее — оно одно в
        списке и стоит сразу. Занятое исполнение выбрать нельзя, поэтому повтор в окне не
        собирается и предупреждать не о чем.

        После записи исполнения номер остается выбранным, а исполнение встает на следующее
        свободное: код ЕСКД, наименование и примечания тоже остаются — документ тот же. После
        записи нового документа он переезжает в группу «Без исполнения», а выбор возвращается на
        новый номер, уже следующий.

        ## Код ЕСКД

        Под полем открыт встроенный классификатор — 78 481 строка всех пяти уровней. Открыт он на
        классах и раскрывается вглубь: щелчок по строке показывает следующий уровень, и так до
        полного шестизначного кода. Уровень видно по точкам после кода, дополняющим его до шести
        знаков: `38 ....` класс, `380 ...` подкласс, `3800 ..` группа, `38000 .` подгруппа,
        `380008` вид. Есть точки — строка раскроется, нет точек — строку можно выбрать.

        Знаете код заранее — наберите цифры, и список покажет всю дорогу к нему сверху вниз.
        Наберете слово — найдутся строки по наименованию на любом уровне. Стрелками ↑ ↓ выбрать,
        **Enter** делает то же, что щелчок. Код и наименование подставляются в поля, наименование
        потом можно поправить.

        ## Куда пишется

        В выбранную коллекцию, у которой ровно эти столбцы и в этом порядке:

        | № | Столбец | Что попадает |
        |---|---|---|
        | 1 | Наименование | наименование ЕСКД (оно же название записи) |
        | 2 | Обозначение | собранное обозначение |
        | 3 | ФИО регистрирующего | введенное ФИО |
        | 4 | Дата регистрации | дата и время нажатия «Зарегистрировать» |
        | 5 | Проект | обязательное поле окна |
        | 6 | Отметка учета | необязательное поле окна |
        | 7 | Примечание (первичное применение) | необязательное поле окна |
        | 8 | Примечание (краткая характеристика) | необязательное поле окна |

        Коллекция с другим набором или порядком столбцов отклоняется с сообщением
        «Вы выбрали неправильную коллекцию» — записать в нее ничего нельзя.

        ## Загрузка списком из файла

        Список сверху окна переключает способ работы:

        - **Ручное регистрирование номеров КД** — по умолчанию, все описанное выше;
        - **Загрузить файл со списком номеров КД** — заносит в журнал готовый список разом.

        В режиме файла доступны только поле со ссылкой на файл, кнопка «Обзор», база и коллекция;
        остальные поля гаснут — значения берутся из файла. Рамка классификатора занята разбором
        файла: там либо ошибки с номерами строк, либо перечень того, что будет записано, с уже
        выданными номерами.

        Файл — книга `.xlsx` или `.xlsm`; читается ПЕРВЫЙ лист, первая строка — заголовок, столбцы
        те же восемь и в том же порядке, что в журнале. Пустые строки между блоками пропускаются.

        ### Обозначение в файле — шаблон

        **Номера в файле не пишут** — их выдает расширение, как и при ручной регистрации. В
        столбце «Обозначение» указывают только то, что известно составителю списка, а на месте
        номера ставят метку `ХХХ` (и `ХХ` на месте исполнения):

        Годных сочетаний ровно два — те же, что и в окне: новый документ либо исполнение уже
        выданного.

        | В файле | Что запишется |
        |---|---|
        | `АБВГ.301121.ХХХ` | `АБВГ.301121.014` — первый свободный номер серии |
        | `АБВГ.301121.014-ХХ` | `АБВГ.301121.014-01` — **исполнение документа 014**: номер ваш, исполнение выдается |
        | `АБВГ.301121.ХХХ-ХХ` | **ошибка**: новому номеру исполнение не назначают — номер еще не выдан, и приписывать его не к чему |
        | `АБВГ.301121.014` | **ошибка**: номер сам по себе выдает расширение |
        | `АБВГ.301121.014-01` | **ошибка**: исполнение тоже выдает расширение — нужно `014-ХХ` |

        Метку принимаем и латинской буквой, и кириллической, в любом регистре — на клавиатуре они
        на одной клавише.

        **Номер называют только под исполнение** — так исполнение приписывают к уже выданному
        документу. Выдается первое свободное исполнение этого номера: нет ни одного — `-01`, есть
        `-01` и `-02` — выйдет `-03`. Документа с таким номером в журнале может не быть вовсе —
        исполнение все равно заведется, а сам номер после этого считается занятым. Этим файл и
        отличается от окна: в окне выбирают из выданных номеров, в файле номер называют любой.

        **Каждая строка файла — своя запись**, даже если строки одинаковы: два
        `АБВГ.301121.ХХХ` подряд дадут `…014` и `…015`, а два `АБВГ.301121.014-ХХ` — `…014-01` и
        `…014-02`. Номера и исполнения раздаются подряд по ходу файла, у каждой серии свой счет.

        ### Что проверяется

        | Что | Требование |
        |---|---|
        | Обозначение | `АААА.000000.ХХХ` или `АААА.000000.000-ХХ` |
        | Код организации | из списка настроек расширения — так же ловится латиница, набранная вместо кириллицы |
        | Наименование | заполнено |
        | ФИО регистрирующего | написано полностью: Фамилия Имя Отчество — «Иванов И.И.» не пройдет |
        | Проект | заполнен |
        | Отметка учета, оба примечания | необязательны |

        Столбец **«Дата регистрации»** в файле быть обязан, но значение из него не берется: дата
        регистрации — это момент, когда строка попала в журнал, и ставится он при записи. Что бы
        в ячейке ни стояло, оно не читается и ошибкой не бывает.

        Файл записывается **целиком или никак**: пока в нем есть хоть одна ошибка, не пишется ни
        одна строка. Наполовину залитый журнал разобрать нечем — часть номеров выдана, часть нет.
        Поправили файл — выберите его через «Обзор» еще раз, и он перечитается.

        Перед записью окно спросит подтверждение и назовет число строк. Номера при этом выдаются
        заново, по свежему журналу: между разбором файла и нажатием кнопки их мог занять другой
        регистратор. Дальше появляется окно с процентами — то же, что при удалении коллекции; его
        «Отмена» откатывает запись целиком, в журнале не остается ни одной строки.

        Записанный файл снимается с разбора — чтобы занести его повторно (это будут уже другие
        документы с новыми номерами), файл надо выбрать заново.

        ## Перед первым запуском

        В разделе **Настройки → Расширения** укажите коды организации через запятую
        (`АБВГ, ГМБВ`) — из них собирается выпадающий список в окне. Там же можно сразу вписать
        ФИО: окно подставит его при открытии, а после регистрации запишет обратно то, что стоит
        в поле, — значение одно и то же в обоих местах.

        Еще два поля — **База данных журнала** и **Коллекция журнала регистрации** — заполнять
        руками не нужно: их ведет само окно. Выбрали базу и коллекцию один раз — в следующий раз
        они подставятся сами. Видны они здесь затем, чтобы их можно было посмотреть, очистить или
        задать заранее.

        ## Особенности

        - Окно остается открытым: ФИО, код организации, база и коллекция сохраняются для
          следующего документа, код ЕСКД, наименование, проект и примечания очищаются.
        - Номер подбирается в момент записи, а не в момент показа: если тот же номер успел занять
          другой регистратор, документ получит следующий свободный.
        - Записи дописываются в конец коллекции — в порядке выдачи номеров.
        - Способ регистрации и путь к файлу между запусками не помнятся: это выбор под задачу, а
          не настройка рабочего места. Окно всегда открывается на ручной регистрации.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    /// <summary>
    /// Четыре поля, которые расширению негде взять самому. Первые два человек вводит руками
    /// (у предприятия свои коды, у машины одно ФИО), вторые два ведет само окно: выбрал базу и
    /// коллекцию — они тут же тут и записались, а в следующий раз подставились. Показываются
    /// они здесь затем, чтобы их было видно и можно было очистить или задать заранее — например
    /// на новой машине, не открывая расширение.
    /// </summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(OrgCodesKey,   "Коды организации (через запятую)", "АБВГ, ГМБВ"),
        new(FioKey,        "ФИО регистрирующего",              "Иванов Иван Иванович"),
        new(DatabaseKey,   "База данных журнала",              "Имя базы из списка баз"),
        new(CollectionKey, "Коллекция журнала регистрации",    "Журнал регистрации"),
    ];

    public Window? CreateWindow() => new DocRegistryWindow();

    /// <summary>
    /// Разобрать строку настройки в список кодов организации: разделители — запятая, точка с
    /// запятой и перевод строки, крайние пробелы снимаются, пустые куски и повторы выбрасываются.
    /// Порядок — как ввел человек: первый код станет выбранным по умолчанию.
    /// </summary>
    public static IReadOnlyList<string> ParseOrgCodes(string? raw)
    {
        var seen  = new HashSet<string>(StringComparer.CurrentCultureIgnoreCase);
        var codes = new List<string>();

        foreach (var part in (raw ?? "").Split([',', ';', '\n', '\r'], StringSplitOptions.RemoveEmptyEntries))
        {
            var code = part.Trim();
            if (code.Length > 0 && seen.Add(code)) codes.Add(code);
        }

        return codes;
    }
}
