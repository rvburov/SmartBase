using Avalonia.Controls;

namespace SmartBase.Extensions.DocRegistry;

/// <summary>
/// Расширение «Регистрация КД»: выдает документу обозначение по ГОСТ 2.201-80
/// (<c>код организации.код ЕСКД.номер</c>) и заводит строку в журнале регистрации — готовой
/// коллекции с восемью столбцами (см. <see cref="RegistrySchema"/>). Запускается отдельным
/// окном (<see cref="DocRegistryWindow"/>) в основном стиле приложения.
///
/// Логика вынесена целиком из UI: <see cref="Designation"/> — обозначения и номера,
/// <see cref="EskdCatalog"/> — справочник ЕСКД, <see cref="RegistrySchema"/> — эталон
/// коллекции, <see cref="DocRegistrar"/> — сама запись. Расширение самостоятельно и зависит
/// только от <see cref="IExtension"/> + публичного API работы с базами
/// (RelationDbResolver/ConstructorRepository), как «Документы в коллекцию».
/// </summary>
public sealed class DocRegistryExtension : IExtension
{
    public const string ExtensionId = "doc-registry";

    /// <summary>Настройка: коды организации через запятую — из них собирается выпадающий список.</summary>
    public const string OrgCodesKey = "orgs";

    /// <summary>
    /// Настройка: ФИО регистратора. Объявлена настройкой, а не спрятана внутри окна, потому что
    /// у машины она одна и меняется редко — вводить ее заново на каждый документ незачем. Окно
    /// подставляет значение при открытии и записывает обратно после регистрации, поэтому
    /// поправить ФИО можно и там, и на экране настроек — это одно и то же значение.
    /// </summary>
    public const string FioKey = "fio";

    /// <summary>
    /// Настройка: база данных, в которой лежит журнал регистрации, — по ИМЕНИ из списка баз.
    /// Восстанавливается при открытии окна; имя не нашлось (базу переименовали или отключили) —
    /// берется первая база, как и раньше.
    /// </summary>
    public const string DatabaseKey = "database";

    /// <summary>
    /// Настройка: коллекция-журнал, в которую пишутся регистрации, — по ИМЕНИ внутри выбранной
    /// базы. Имя не нашлось — не выбирается НИЧЕГО: наугад взятая первая коллекция тут же
    /// отвечала бы «Вы выбрали неправильную коллекцию» на пустом месте.
    /// </summary>
    public const string CollectionKey = "collection";

    public string Id   => ExtensionId;
    public string Name => "Регистрация КД";

    public string MarkdownDescription =>
        """
        Выдает конструкторскому документу обозначение по ГОСТ 2.201-80 и заводит строку в журнале
        регистрации — коллекции программы.

        **Обозначение**

        Собирается по маске `Код организации` . `Код ЕСКД` . `Порядковый номер`, например
        `АБВГ.301121.001`. Номер — первый свободный в своей серии: если у этой пары «организация
        + код ЕСКД» заняты 001 и 003, документ получит 002. У каждого кода ЕСКД нумерация своя.

        **Код ЕСКД**

        Под полем сразу открыт весь встроенный классификатор — 66 186 шестизначных кодов. Можно
        пролистать список, а можно отфильтровать: цифры ищут по коду, слово — по наименованию.
        Стрелками ↑ ↓ выбрать, **Enter** — зафиксировать (или щелкнуть строку мышью). Выбранная
        строка остается выделенной, код и наименование подставляются в поля, а наименование потом
        можно поправить.

        **Куда пишется**

        В выбранную коллекцию, у которой ровно эти столбцы и в этом порядке:

        | № | Столбец | Что попадает |
        |---|---|---|
        | 1 | Наименование | наименование ЕСКД (оно же название записи) |
        | 2 | Обозначение | собранное обозначение |
        | 3 | Фамилия, имя, отчество | введенное ФИО |
        | 4 | Дата регистрации | дата и время нажатия «Зарегистрировать» |
        | 5 | Тема | необязательное поле окна |
        | 6 | Отметка учёта | необязательное поле окна |
        | 7 | Примечания (первичное применение) | необязательное поле окна |
        | 8 | Примечание (краткая характеристика) | необязательное поле окна |

        Коллекция с другим набором или порядком столбцов отклоняется с сообщением
        «Вы выбрали неправильную коллекцию» — записать в нее ничего нельзя.

        **Перед первым запуском**

        В разделе **Настройки → Расширения** укажите коды организации через запятую
        (`АБВГ, ГМБВ`) — из них собирается выпадающий список в окне. Там же можно сразу вписать
        ФИО: окно подставит его при открытии, а после регистрации запишет обратно то, что стоит
        в поле, — значение одно и то же в обоих местах.

        Ещё два поля — **База данных журнала** и **Коллекция журнала регистрации** — заполнять
        руками не нужно: их ведёт само окно. Выбрали базу и коллекцию один раз — в следующий раз
        они подставятся сами. Видны они здесь затем, чтобы их можно было посмотреть, очистить или
        задать заранее.

        **Особенности**
        - Окно остается открытым: ФИО, код организации, база и коллекция сохраняются для
          следующего документа, код ЕСКД и наименование очищаются.
        - Номер подбирается в момент записи, а не в момент показа: если тот же номер успел занять
          другой регистратор, документ получит следующий свободный.
        - Записи дописываются в конец коллекции — в порядке выдачи номеров.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    /// <summary>
    /// Четыре поля, которые расширению негде взять самому. Первые два человек вводит руками
    /// (у предприятия свои коды, у машины одно ФИО), вторые два ведет само окно: выбрал базу и
    /// коллекцию — они тут же тут и записались, а в следующий раз подставились. Показываются
    /// они здесь затем, чтобы их было видно и можно было очистить или задать заранее — например
    /// на новой машине, не открывая расширение.
    /// </summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(OrgCodesKey,   "Коды организации (через запятую)", "АБВГ, ГМБВ"),
        new(FioKey,        "Фамилия, имя, отчество",           "Иванов Иван Иванович"),
        new(DatabaseKey,   "База данных журнала",              "Имя базы из списка баз"),
        new(CollectionKey, "Коллекция журнала регистрации",    "Журнал регистрации"),
    ];

    public Window? CreateWindow() => new DocRegistryWindow();

    /// <summary>
    /// Разобрать строку настройки в список кодов организации: разделители — запятая, точка с
    /// запятой и перевод строки, крайние пробелы снимаются, пустые куски и повторы выбрасываются.
    /// Порядок — как ввел человек: первый код станет выбранным по умолчанию.
    /// </summary>
    public static IReadOnlyList<string> ParseOrgCodes(string? raw)
    {
        var seen  = new HashSet<string>(StringComparer.CurrentCultureIgnoreCase);
        var codes = new List<string>();

        foreach (var part in (raw ?? "").Split([',', ';', '\n', '\r'], StringSplitOptions.RemoveEmptyEntries))
        {
            var code = part.Trim();
            if (code.Length > 0 && seen.Add(code)) codes.Add(code);
        }

        return codes;
    }
}
