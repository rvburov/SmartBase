    /// <summary>
    /// Первые два действия вместе складывают путь сообщения из папки обмена: разобрать текст
    /// (<see cref="ParseMessageAction"/>) и зарегистрировать разобранное
    /// (<see cref="RegisterAction"/>). Регистрация — та же самая, что в окне: сообщение из папки
    /// обмена становится четвертым способом позвать одно и то же, рядом с окном и загрузкой
