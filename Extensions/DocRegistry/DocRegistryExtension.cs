using Avalonia.Controls;

namespace SmartBase.Extensions.DocRegistry;

/// <summary>
/// Расширение «Регистрация КД»: выдает документу обозначение по ГОСТ 2.201-80
/// (<c>код организации.код ЕСКД.номер</c>) и заводит строку в журнале регистрации — готовой
/// коллекции с восемью столбцами (см. <see cref="RegistrySchema"/>). Запускается отдельным
/// окном (<see cref="DocRegistryWindow"/>) в основном стиле приложения.
///
/// Второй способ работы — загрузка готового списка номеров файлом: номера в нем уже выданы,
/// расширение их проверяет и заносит в журнал разом (<see cref="RegistryFile"/>,
/// <see cref="RegistryImport"/>).
///
/// Логика вынесена целиком из UI: <see cref="Designation"/> — обозначения и номера,
/// <see cref="EskdCatalog"/> — справочник ЕСКД, <see cref="RegistrySchema"/> — эталон
/// коллекции, <see cref="DocRegistrar"/> — сама запись. Расширение самостоятельно и зависит
/// только от <see cref="IExtension"/> + публичного API работы с базами
/// (RelationDbResolver/ConstructorRepository), как «Документы в коллекцию».
/// </summary>
public sealed class DocRegistryExtension : IExtension
{
    public const string ExtensionId = "doc-registry";

    /// <summary>Настройка: коды организации через запятую — из них собирается выпадающий список.</summary>
    public const string OrgCodesKey = "orgs";

    /// <summary>
    /// Настройка: ФИО регистратора. Объявлена настройкой, а не спрятана внутри окна, потому что
    /// у машины она одна и меняется редко — вводить ее заново на каждый документ незачем. Окно
    /// подставляет значение при открытии и записывает обратно после регистрации, поэтому
    /// поправить ФИО можно и там, и на экране настроек — это одно и то же значение.
    /// </summary>
    public const string FioKey = "fio";

    /// <summary>
    /// Настройка: база данных, в которой лежит журнал регистрации, — по ИМЕНИ из списка баз.
    /// Восстанавливается при открытии окна; имя не нашлось (базу переименовали или отключили) —
    /// берется первая база, как и раньше.
    /// </summary>
    public const string DatabaseKey = "database";

    /// <summary>
    /// Настройка: коллекция-журнал, в которую пишутся регистрации, — по ИМЕНИ внутри выбранной
    /// базы. Имя не нашлось — не выбирается НИЧЕГО: наугад взятая первая коллекция тут же
    /// отвечала бы «Вы выбрали неправильную коллекцию» на пустом месте.
    /// </summary>
    public const string CollectionKey = "collection";

    /// <summary>
    /// Настройка: кто может регистрировать по сообщениям — идентификаторы отправителей через
    /// точку с запятой, после идентификатора можно дописать имя для себя. Пусто — никто:
    /// регистрацию по переписке включают осознанно, а не обнаруживают
    /// (<see cref="RegisterMessageAction"/>).
    /// </summary>
    public const string SendersKey = "senders";

    /// <summary>Подпись настройки <see cref="SendersKey"/> — ее же называет отказ действия.</summary>
    public const string SendersLabel = "Кто регистрирует по сообщениям";

    public string Id   => ExtensionId;
    public string Name => "Регистрация КД";

    public string MarkdownDescription =>
        """
        Выдает конструкторскому документу обозначение по ГОСТ 2.201-80 и заводит строку в
        журнале регистрации — обычной коллекции программы. Номер расширение подбирает само,
        по самому журналу: отдельного счетчика, который можно сбить, нет.

        Работать можно двумя способами, и переключает их список сверху окна: **по одному
        документу**, когда номер выдает расширение прямо в окне, или **списком из файла**,
        когда надо занести в журнал целую пачку разом.

        ## Что делает

        ### Обозначение

        Собирается по маске `Код организации.Код ЕСКД.Порядковый номер`, например
        `АБВГ.301121.001`. Номер — первый свободный в своей серии: счетчика расширение не хранит,
        а перед каждой записью заново читает столбец «Обозначение» коллекции и берет первый
        незанятый номер, считая с 001. Серия — пара «организация + код ЕСКД», у каждой пары своя
        нумерация 001–999.

        | В журнале по серии `АБВГ.301121.` | Новый номер |
        |---|---|
        | пусто | 001 |
        | 001, 002, 003 | 004 |
        | 001, 003 | 002 — дырки заполняются |
        | строку с 002 удалили | 002 — номер освободился |
        | только `АБВГ.723611.001` | 001 — другая серия |
        | заняты все 001–999 | отказ |

        **Занимают номер** и повторно его выдать не дают: исполнение `…001-01`, свернутые
        исполнения `…001 (01-19)`, приписки `…001 (копия)` и `…001СБ` (хвост читается до первой
        нецифры), строчные буквы в коде организации, лишние пробелы по краям.

        **Не занимают номер** — такие строки пропускаются целиком, и номер по ним уйдет второй
        раз (их в журнале надо исправлять):

        | Строка | Почему пропускается |
        |---|---|
        | `…0011` — четыре цифры | не номер по ГОСТ: занял бы номер 11 по ошибке разбора |
        | `…01` — две цифры | это и 001, и обрубок 011 или 014 — гадать нельзя |
        | `АБВГ.301121. 001` | пробел после точки: в начале хвоста нет цифр |
        | `АБВГ.301121-001` | дефис вместо точки: приставка серии не совпала |
        | латинская буква в коде организации | для программы это другая серия |
        | `…000` | номера 000 не бывает |
        | два обозначения в одной ячейке | читается только первое |

        ### Номер и исполнение

        Обозначение в окне собрано в один ряд из своих частей — код организации, код ЕСКД, номер и
        исполнение, — и читается как готовый номер: `АБВГ.301121.012-01`.

        **Номер выбирают из списка.** Как только введен код ЕСКД, список наполняется по серии:

        | В списке | Что это |
        |---|---|
        | **Новый номер** | первый свободный номер серии |
        | **Без исполнения** | выданные номера, у которых исполнений еще нет |
        | **С исполнением** | выданные номера, у которых исполнения уже есть |

        Заголовки групп выбраться не могут, а пустая группа не показывается. В самом поле стоит
        только номер, поэтому ряд по-прежнему читается как обозначение.

        Выбор номера и решает, что регистрируется:

        | Выбрано | Исполнение | Запишется |
        |---|---|---|
        | Новый номер `014` | **недоступно** | `АБВГ.301121.014` |
        | `001` (без исполнения) | `01` | `АБВГ.301121.001-01` |
        | `003` (есть `01`, `02`) | `03` | `АБВГ.301121.003-03` |

        **Исполнение не выбирают**: у выбранного номера свободно только следующее — оно одно в
        списке и стоит сразу. Занятое исполнение выбрать нельзя, поэтому повтор в окне не
        собирается и предупреждать не о чем.

        ### Код ЕСКД

        Под полем открыт встроенный классификатор — 78 481 строка всех пяти уровней. Открыт он на
        классах и раскрывается вглубь: щелчок по строке показывает следующий уровень, и так до
        полного шестизначного кода. Уровень видно по точкам после кода, дополняющим его до шести
        знаков: `38 ....` класс, `380 ...` подкласс, `3800 ..` группа, `38000 .` подгруппа,
        `380008` вид. Есть точки — строка раскроется, нет точек — строку можно выбрать.

        Знаете код заранее — наберите цифры, и список покажет всю дорогу к нему сверху вниз.
        Наберете слово — найдутся строки по наименованию на любом уровне. Стрелками ↑ ↓ выбрать,
        **Enter** делает то же, что щелчок. Код и наименование подставляются в поля, наименование
        потом можно поправить. Клавиша **Esc** возвращает список к классам.

        ## Перед первым запуском

        Нужны две вещи: заполненные настройки и готовая коллекция-журнал.

        ### Настройки расширения

        Пять полей в разделе **Настройки → Расширения**, и заполняются они по-разному:

        | Поле | Кто заполняет | Что в нем |
        |---|---|---|
        | Коды организации (через запятую) | **вы, руками** | `АБВГ, ГМБВ` — из них соберется выпадающий список в окне |
        | ФИО регистрирующего | вы или окно | подставляется при открытии; после каждой регистрации окно пишет обратно то, что стоит в поле |
        | База данных журнала | окно | запоминается при выборе |
        | Коллекция журнала регистрации | окно | запоминается при выборе |
        | Кто регистрирует по сообщениям | **вы, руками** | нужно только для регистрации по сообщению — см. ниже |

        **Пока коды организации не заданы, регистрировать нельзя**: обозначение без кода
        организации не собрать. Это единственное поле, которое обязательно заполнить руками —
        коды у каждого предприятия свои.

        Последние два поля заполнять руками не надо: выбрали базу и коллекцию один раз — дальше
        они подставятся сами, и при следующем открытии окна останется только выбрать код ЕСКД.
        Видны они в настройках затем, чтобы их можно было посмотреть, очистить или задать
        заранее на новой машине.

        > Запоминается только выбор, на котором можно работать: если у коллекции не та
        > структура, она в настройки не запишется.

        ### Журнал регистрации

        Это обычная коллекция программы, которую вы заводите сами — расширение ее не создает, а
        только дописывает в нее строки. Столбцов должно быть ровно восемь и ровно в таком
        порядке:

        | № | Столбец | Тип |
        |---|---|---|
        | 1 | Наименование | системный столбец записи — переименуйте «Название» |
        | 2 | Обозначение | текст |
        | 3 | ФИО регистрирующего | текст |
        | 4 | Дата регистрации | дата |
        | 5 | Проект | текст |
        | 6 | Отметка учета | текст |
        | 7 | Примечание (первичное применение) | текст |
        | 8 | Примечание (краткая характеристика) | текст |

        Коллекция с другим набором или порядком столбцов отклоняется с сообщением
        **«Вы выбрали неправильную коллекцию»**, и окно называет, какой столбец не на месте.
        Кнопка «Зарегистрировать» при этом остается выключенной — записать что-то не туда
        нельзя.

        Регистр букв и лишние пробелы в названиях столбцов расширение прощает, а вот порядок —
        нет: переставленные столбцы означают, что значения легли бы не туда.

        ## Как пользоваться

        Список сверху окна стоит на **«Ручное регистрирование номеров КД»** — так окно и
        открывается.

        1. Проверьте **ФИО регистрирующего** — обычно оно уже подставлено с прошлого раза.
        2. Выберите **код организации** из списка.
        3. Выберите **код ЕСКД** в классификаторе под полем.
        4. Выберите **базу данных** и **коллекцию** журнала. В следующий раз этот шаг можно
           будет пропустить — выбор запомнится.
        5. Выберите **номер** из списка: «Новый номер» для нового документа либо уже выданный
           номер, если регистрируете его исполнение.
        6. Заполните **Проект** — поле обязательное: пока оно пустое, кнопка выключена, а в окне
           стоит подсказка «Заполните проект».
        7. При необходимости заполните **Отметку учета** и два **Примечания** — они
           необязательны, пустые столбцы останутся пустыми.
        8. Нажмите **«Зарегистрировать»**. Перед нажатием в окне видно, какое обозначение
           получится: «Будет присвоено: АБВГ.301121.003-03».

        ### Загрузка списком из файла

        Так регистрируют целый список документов разом. Номера расширение выдает само — те же,
        что выдало бы вручную.

        Выберите в списке сверху **«Загрузить файл со списком номеров КД»**: станут доступны поле
        со ссылкой на файл и кнопка «Обзор», а поля документа погаснут — значения для них
        берутся из файла. Доступными останутся только база данных и коллекция.

        Рамка классификатора при этом занята разбором файла: там либо список ошибок с номерами
        строк, либо перечень того, что будет записано, с уже выданными номерами.

        Файл — книга `.xlsx` или `.xlsm`; читается **первый лист**, первая строка — заголовок,
        столбцы те же восемь и в том же порядке, что в журнале. Пустые строки между блоками
        пропускаются. Проще всего сделать такой файл выгрузкой самого журнала: столбцы уже те,
        что нужно, — останется очистить лишнее и поставить в обозначениях метки.

        ### Регистрация по сообщению

        Третий способ — без окна: сотрудник пишет сообщение, программа регистрирует документ и
        отвечает ему. Сообщение приходит из сторонней программы шагом сценария (**Настройки →
        Интеграции**), а расширение делает все остальное: разбирает текст, проверяет, выдает
        номер и составляет ответ.

        Сообщение — пять строк «Ключ: значение», порядок строк не важен:

        ```
        Действие: Регистрация
        Номер: АБВГ.301121.ХХХ
        Наименование: Кронштейн
        Проект: Машина
        ФИО: Иванов Иван Иванович
        ```

        | Строка | Что в ней |
        |---|---|
        | Действие | `Регистрация` |
        | Номер | `АБВГ.301121.ХХХ` — новый документ, номер выдаст расширение; `АБВГ.301121.001-ХХ` — следующее исполнение документа 001 |
        | Наименование | наименование документа |
        | Проект | проект |
        | ФИО | полностью: Фамилия Имя Отчество |

        Можно указать полный свободный номер без исполнения, например `АБВГ.301121.001`;
        занятый номер не принимается. Готовое исполнение не указывают — его выдает расширение.
        Код организации сверяется со списком из настроек. Буквы,
        одинаковые на вид в обеих раскладках, принимаются в любой: `ХХХ` и код организации можно
        набрать, не переключая клавиатуру.

        **Подтверждение регистрации.** Если серия организации и классификации еще пуста и
        выдается `001`, ответ показывает полный номер и расшифровку кода ЕСКД по уровням.
        Если в новой серии код отсутствует в доступном справочнике, ответ предупреждает,
        что он, возможно, относится к закрытому классификатору. Напишите отдельным сообщением
        `Да` для регистрации или `Нет` для отмены. До `Да` записи нет. Подтверждение действует
        10 минут, используется один раз и проверяет права и неизменность серии повторно.
        Последующие документы существующей серии регистрируются без этого подтверждения.

        Каждая строка сообщения набирается с новой строки — как обычно в переписке. Если
        программа, из которой приходят сообщения, передает переносы строк разметкой, расширение
        читает такой текст так же.

        **Ответ, если все верно, — что зарегистрировано: те же строки, с выданным номером:**

        ```
        Зарегистрировано
        Номер: АБВГ.301121.014
        Наименование: Кронштейн
        Проект: Машина
        ФИО: Иванов Иван Иванович
        ```

        **Если в сообщении ошибки — все сразу, по строке на каждую:**

        ```
        Номер: неправильный номер (Пример: АААА.000000.ХХХ или АААА.000000.001-ХХ)
        Проект: не указан проект
        ФИО: не полное ФИО (Пример: Иванов Иван Иванович)
        ```

        #### Просмотр, удаление и изменение по сообщению

        В том же шаге сценария доступны четыре действия: `Регистрация`, `Просмотр`,
        `Удаление`, `Изменение`. Для трех последних указывают уже выданный полный номер,
        включая исполнение, если нужно: `АБВГ.301121.001-01`. Метки `ХХХ` здесь не подходят.

        **Просмотр** возвращает все восемь столбцов журнала, без подтверждения:

        ```
        Действие: Просмотр
        Номер: АБВГ.301121.001
        ```

        **Удаление** сначала показывает карточку документа и просит подтверждение:

        ```
        Действие: Удаление
        Номер: АБВГ.301121.001
        ```

        **Изменение** принимает только те поля, которые нужно заменить: `Наименование`,
        `Проект`, `ФИО`. Номер и дата регистрации сохраняются. Пустые значения не принимаются;
        ФИО — полностью. Например, заменить только проект:

        ```
        Действие: Изменение
        Номер: АБВГ.301121.001
        Проект: Станок
        ```

        До записи программа показывает текущую карточку и изменения «старое → новое».
        На запрос подтверждения отправьте отдельным сообщением **Да** или **Нет**.
        Регистр не важен: `да`, `ДА`, `нет`, `НЕТ` также принимаются.
        `Да` выполняет операцию один раз; `Нет` отменяет. Подтверждение действует 10 минут,
        только для того же отправителя, базы и журнала. После закрытия базы или перезапуска
        запрос нужно отправить заново. Пока операция ожидает ответа, заменить ее другой
        нельзя: сначала ответьте `Нет`. Просматривать документы в это время можно.

        Если запись изменилась, удалена или номер неоднозначен, операция не выполняется:
        ответ называет причину. Ошибки полей возвращаются вместе. Если документ не найден,
        ответ — `Номер: документ АБВГ.301121.001 не найден`. После удаления номер может снова
        выдаваться при регистрации — как любой свободный номер серии.

        Все сообщения, включая отдельные `Да` и `Нет`, должны доходить до того же шага
        сценария: отбор только сообщений со строкой `Действие:` отрежет подтверждения.

        Отправьте отдельным сообщением `Инструкция`, чтобы получить правила и примеры всех четырех
        действий. Команда доступна тому же списку сотрудников, не меняет журнал и не сбрасывает
        ожидающее подтверждение. Ответ — обычный текст с переносами строк; для программы-мессенджера
        разделитель задается полем «Перенос строки в ответе» сценария. Сообщение `Инструкция` также
        должно проходить отбор сценария.

        #### Кто может работать по сообщениям

        Только те, кто перечислен в настройке **«Кто регистрирует по сообщениям»**. В ней —
        идентификаторы отправителей через точку с запятой; после идентификатора можно дописать
        имя, чтобы список читался:

        ```
        1001 Иванов; 1002 Петров
        ```

        Идентификатор — то, чем программа, из которой приходят сообщения, называет отправителя.
        Сверяется он, а не строка «ФИО» сообщения: ее можно написать любую. Остальные получают
        ответ «Вы не в списке регистрирующих». Пока список пуст, по сообщениям не регистрирует
        никто. Тот же список разрешает просмотр, удаление и изменение. Дополнительно
        проверяются права текущего подключения к базе: просмотр коллекции, изменение или
        удаление записи. При подтверждении права проверяются снова.

        #### Настройка шага

        В сценарии ставится шаг **«Действие» → «Регистрация КД: Зарегистрировать по сообщению»**,
        коллекция — журнал регистрации, и два поля:

        | Поле шага | Что в него поставить |
        |---|---|
        | Текст сообщения | колонку события с текстом, в двойных фигурных скобках |
        | Отправитель | колонку события с идентификатором отправителя |

        Как называются эти колонки, зависит от программы, из которой приходят сообщения: это
        имена полей ее события.

        #### Обозначение в файле — шаблон

        **Номера в файле не пишут** — их выдает расширение, как и при ручной регистрации. В
        столбце «Обозначение» указывают только то, что известно составителю списка, а на месте
        номера ставят метку `ХХХ` (и `ХХ` на месте исполнения).

        Годных сочетаний ровно два — те же, что и в окне: новый документ либо исполнение уже
        выданного.

        | В файле | Что запишется |
        |---|---|
        | `АБВГ.301121.ХХХ` | `АБВГ.301121.014` — первый свободный номер серии |
        | `АБВГ.301121.014-ХХ` | `АБВГ.301121.014-01` — **исполнение документа 014**: номер ваш, исполнение выдается |
        | `АБВГ.301121.ХХХ-ХХ` | **ошибка**: новому номеру исполнение не назначают — номер еще не выдан, и приписывать его не к чему |
        | `АБВГ.301121.014` | **ошибка**: номер сам по себе выдает расширение |
        | `АБВГ.301121.014-01` | **ошибка**: исполнение тоже выдает расширение — нужно `014-ХХ` |

        Метку принимаем и латинской буквой, и кириллической, в любом регистре — на клавиатуре они
        на одной клавише.

        **Номер называют только под исполнение** — так исполнение приписывают к уже выданному
        документу. Выдается первое свободное исполнение этого номера: нет ни одного — `-01`, есть
        `-01` и `-02` — выйдет `-03`. Документа с таким номером в журнале может не быть вовсе —
        исполнение все равно заведется, а сам номер после этого считается занятым. Этим файл и
        отличается от окна: в окне выбирают из выданных номеров, в файле номер называют любой.

        **Каждая строка файла — своя запись**, даже если строки одинаковы: два
        `АБВГ.301121.ХХХ` подряд дадут `…014` и `…015`, а два `АБВГ.301121.014-ХХ` — `…014-01` и
        `…014-02`. Номера и исполнения раздаются подряд по ходу файла, у каждой серии свой счет.

        #### Что проверяется

        | Что | Требование |
        |---|---|
        | Обозначение | `АААА.000000.ХХХ` или `АААА.000000.000-ХХ` |
        | Код организации | из списка настроек расширения — так же ловится латиница, набранная вместо кириллицы |
        | Наименование | заполнено |
        | ФИО регистрирующего | написано полностью: Фамилия Имя Отчество — «Иванов И.И.» не пройдет |
        | Проект | заполнен |
        | Отметка учета, оба примечания | необязательны |

        Столбец **«Дата регистрации»** в файле быть обязан, но значение из него не берется: дата
        регистрации — это момент, когда строка попала в журнал, и ставится он при записи. Что бы
        в ячейке ни стояло, оно не читается и ошибкой не бывает.

        Файл записывается **целиком или никак**: пока в нем есть хоть одна ошибка, не пишется ни
        одна строка. Наполовину залитый журнал разобрать нечем — часть номеров выдана, часть нет.
        Поправили файл — выберите его через «Обзор» еще раз, и он перечитается.

        Перед записью окно спросит подтверждение и назовет число строк. Дальше появляется окно с
        процентами; его «Отмена» откатывает запись целиком, в журнале не остается ни одной
        строки.

        ## Что получится

        Новая строка (или сразу пачка строк) в выбранной коллекции-журнале:

        | № | Столбец | Что попадает |
        |---|---|---|
        | 1 | Наименование | наименование ЕСКД, оно же название записи |
        | 2 | Обозначение | собранное обозначение |
        | 3 | ФИО регистрирующего | введенное ФИО |
        | 4 | Дата регистрации | дата и время нажатия «Зарегистрировать» |
        | 5 | Проект | обязательное поле окна |
        | 6 | Отметка учета | необязательное поле окна |
        | 7 | Примечание (первичное применение) | необязательное поле окна |
        | 8 | Примечание (краткая характеристика) | необязательное поле окна |

        Записи дописываются в конец коллекции — в порядке выдачи номеров. Дальше это обычные
        строки: их можно править, фильтровать и выгружать средствами таблицы.

        **После записи окно остается открытым** и готовится к следующему документу:

        | Записали | Что дальше в окне |
        |---|---|
        | Новый документ `014` | `014` уезжает в группу «Без исполнения», выбор возвращается на новый номер — уже `015`, поля документа очищаются |
        | Исполнение `003-03` | номер `003` остается выбранным, исполнение встает на следующее свободное `04`, поля документа остаются — документ тот же |
        | Список из файла | в рамке остается перечень записанного с выданными номерами; файл снимается с разбора |

        Регистрация по сообщению окна не касается: строка появляется в журнале, а отправитель
        получает ответ.

        ФИО, код организации, база и коллекция сохраняются в любом случае — регистрировать
        пачкой удобно.

        ## Особенности

        - **Номер подбирается в момент записи**, а не в момент показа: если тот же номер успел
          занять другой регистратор, ваш документ получит следующий свободный. Номера, показанные
          в предпросмотре файла, тоже предварительные и при записи выдаются заново.
        - **Записанный файл снимается с разбора**, и кнопка гаснет: второе нажатие завело бы те
          же документы еще раз, уже под новыми номерами. Если это и нужно — выберите файл через
          «Обзор» заново.
        - **Способ регистрации и путь к файлу между запусками не помнятся**: это выбор под
          задачу, а не настройка рабочего места. Окно всегда открывается на ручной регистрации.
        - **Журнал ведете вы.** Расширение только дописывает строки: удаление строки освобождает
          номер, и он выдастся снова. Строки с обозначениями не по ГОСТ расширение пропускает —
          по ним номер уйдет второй раз, такие записи в журнале надо исправлять.
