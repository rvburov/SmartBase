using Avalonia.Controls;

namespace SmartBase.Extensions;

/// <summary>
/// Контракт самостоятельного расширения. Каждое расширение лежит в своей папке
/// под <c>Extensions/&lt;Имя&gt;/</c> и НИ ОТ ЧЕГО в приложении не зависит, кроме
/// этого интерфейса — оболочка (сайдбар + блок) знает о расширении только через него.
/// </summary>
public interface IExtension
{
    /// <summary>Стабильный идентификатор (ключ строки в сайдбаре).</summary>
    string Id { get; }

    /// <summary>Отображаемое имя — в навбаре блока и в строке сайдбара.</summary>
    string Name { get; }

    /// <summary>Описание расширения в формате Markdown — тело блока.</summary>
    string MarkdownDescription { get; }

    /// <summary>Можно ли запустить расширение прямо сейчас (управляет кнопкой в навбаре).</summary>
    bool CanRun { get; }

    /// <summary>
    /// Настройки расширения — их показывает раздел «Расширения» в настройках приложения.
    /// По умолчанию пусто: расширению без настроек объявлять ничего не нужно. Значения
    /// хранит оболочка по <see cref="Id"/> (см. <see cref="ExtensionSetting"/>), поэтому
    /// список можно менять, не трогая ни экран настроек, ни хранилище.
    /// </summary>
    IReadOnlyList<ExtensionSetting> Settings => [];

    /// <summary>
    /// Создает окно расширения для показа по кнопке «Запустить». Окно строится из
    /// контролов приложения и потому автоматически наследует основной стиль (темы и
    /// ресурсы <c>Application.Styles</c>) — оболочка лишь показывает его поверх главного
    /// окна. Возвращает <c>null</c>, если расширение окно не открывает (например, заглушка
    /// или будущее расширение-надстройка, встраиваемое в блоки приложения).
    /// </summary>
    Window? CreateWindow();
}
