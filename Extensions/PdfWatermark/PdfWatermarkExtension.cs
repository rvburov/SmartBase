using Avalonia.Controls;

namespace SmartBase.Extensions.PdfWatermark;

/// <summary>
/// Контракт расширения «Водяной знак на PDF»: имя, описание и настройки. Вся работа — в
/// <see cref="PdfWatermarkEngine"/> (прогон), <see cref="WatermarkStamp"/> (знак),
/// <see cref="IssueJournal"/> (журнал) и <see cref="PdfWatermarkWindow"/> (окно).
///
/// От соседей отличается тем, что делает две вещи сразу: создает файлы на диске И пишет в чужую
/// готовую коллекцию. Отсюда и проверка структуры выбранной коллекции — как у «Регистрации КД».
/// </summary>
public sealed class PdfWatermarkExtension : IExtension
{
    public const string ExtensionId = "pdf-watermark";

    /// <summary>Текст предупреждения на знаке. Ведет само окно — там его и правят; настройка
    /// держит последнее значение и дает посмотреть или очистить его.</summary>
    public const string WarningKey = "warning";

    /// <summary>Папка для сохранения результата. Ведет само окно, но она стабильна и живет
    /// между запусками.</summary>
    public const string OutputKey = "output";

    /// <summary>Имя базы, где лежит журнал выдачи. Ведет само окно.</summary>
    public const string DatabaseKey = "database";

    /// <summary>Имя коллекции журнала выдачи. Ведет само окно.</summary>
    public const string CollectionKey = "collection";

    /// <summary>Что пишется на знаке, если настройка пуста.</summary>
    public const string DefaultWarning = "Передача третьим лицам запрещена";

    public string Id   => ExtensionId;
    public string Name => "Водяной знак на PDF";

    public string MarkdownDescription =>
        """
        Накладывает на PDF диагональную надпись «кому выдан, какой экземпляр, когда» и заводит
        строку в журнале выдачи — коллекции программы.

        ## Знак

        Три строки по диагонали листа, снизу вверх, серым полупрозрачным — поверх содержимого, на
        каждой странице документа:

        ```
        Выдан: Иванов Иван Иванович
        Экз. № 3 · 29.08.2026
        Передача третьим лицам запрещена
        ```

        Серый и полупрозрачный, чтобы документ под знаком читался целиком. Три строки, а не одна:
        кегль подбирается так, чтобы блок занял диагональ листа, — разбитая надпись садится на тот
        же лист буквами втрое крупнее и заметно крупнее текста самого документа.

        Годится любой PDF: чертеж из САПР, скан-картинка, текстовый документ.

        ## Знак нельзя стереть редактором

        Каждая страница переводится в изображение, и надпись рисуется прямо по его пикселям —
        знак становится частью самой страницы, а не отдельным слоем поверх нее. Выделить его,
        выбрать и удалить, как обычный текст, невозможно: удалять нечего. У букв знака есть еще и
        контур, поэтому не помогает и осветление картинки — оно съедает вместе со знаком сам
        документ.

        Совсем неуничтожимым знак не бывает: пиксели можно закрасить в графическом редакторе
        вручную. Но эта работа идет по тем же местам, где лежит текст документа, следы видны, и
        пакетно на десятки файлов она уже не делается.

        Из этого следует и цена: **в выданном документе не остается текстового слоя** — поиск по
        словам и выделение текста в нем работать не будут. Электронная подпись, если она была,
        становится недействительной.

        ## Номер экземпляра

        Уникален в пределах ДОКУМЕНТА, а документ — это имя файла без расширения. Первый
        свободный: заняты 1 и 3 — выдается 2. У каждого документа нумерация своя, поэтому
        занятый первый экземпляр сборочного чертежа не мешает выдать первый экземпляр
        спецификации.

        Один и тот же документ можно выдать одному и тому же человеку сколько угодно раз — это
        не дубль, экземпляры различаются номером.

        Вводить номер в окне не нужно и негде: он подбирается сам. Если понадобится поправить
        выданный номер, это делается прямо в коллекции журнала — там обычная ячейка.

        ## Куда пишется

        В выбранную коллекцию, у которой ровно эти столбцы и в этом порядке:

        | № | Столбец | Тип | Что попадает |
        |---|---|---|---|
        | 1 | Документ | системный столбец записи | имя файла без расширения |
        | 2 | Экземпляр | Число | выданный номер |
        | 3 | Кому выдан | Текст | введенное ФИО |
        | 4 | Дата выдачи | Дата | дата из окна, без времени |

        У столбца **Дата выдачи** тумблер «Отображать в календаре» должен быть ВЫКЛЮЧЕН — иначе
        каждая выдача станет событием календаря. Коллекция с другим набором, порядком или типом
        столбцов отклоняется с сообщением «Вы выбрали неправильную коллекцию».

        ## Результат

        Новый файл `<имя> экз. N.pdf` в папке для результата. Исходные документы не изменяются. Если файл
        с таким именем уже лежит в папке, к имени приписывается счетчик — `… экз. 3 (2).pdf`.

        ## Перед первым запуском

        Ничего. Текст предупреждения стоит прямо в окне — по умолчанию «Передача третьим лицам
        запрещена», правится под конкретную выдачу и запоминается на следующий раз. Папка для
        результата, база и коллекция тоже запоминаются: выбрали один раз — дальше подставятся
        сами. Посмотреть или очистить сохраненное можно в разделе **Настройки → Расширения**.

        ## Особенности

        - Окно остается открытым: получатель, дата, база и коллекция сохраняются для следующей
          выдачи.
        - Защищенные паролем и поврежденные файлы пропускаются со строкой в журнале окна —
          пачка идет дальше.
        - Большие пачки идут ровно: 20 000 документов — около четверти часа, и последний файл
          обрабатывается с той же скоростью, что и первый.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    /// <summary>
    /// Четыре поля, которые ведет само окно. Показаны они здесь затем, чтобы их было видно и
    /// можно было очистить или задать заранее на новой машине.
    ///
    /// ФИО получателя настройкой сознательно НЕ объявлено, в отличие от «Регистрации КД»: там
    /// ФИО принадлежит машине и меняется редко, здесь получатель меняется на каждую выдачу, и
    /// подставлять чужую фамилию из настроек нельзя.
    /// </summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(WarningKey,    "Текст предупреждения на знаке", DefaultWarning),
        new(OutputKey,     "Папка для сохранения результата", "Куда класть документы со знаком"),
        new(DatabaseKey,   "База данных журнала",           "Имя базы из списка баз"),
        new(CollectionKey, "Коллекция журнала выдачи",      "Журнал выдачи"),
    ];

    public Window? CreateWindow() => new PdfWatermarkWindow();

    /// <summary>Текст предупреждения: пусто в настройках — значение по умолчанию. Знак без
    /// предупреждения смысл теряет, поэтому пустым он не остается.</summary>
    public static string Warning(string? raw) =>
        (raw ?? "").Trim() is { Length: > 0 } text ? text : DefaultWarning;
}
