using Avalonia.Controls;

namespace SmartBase.Extensions.PdfWatermark;

/// <summary>
/// Контракт расширения «Водяной знак на PDF»: имя, описание и настройки. Вся работа — в
/// <see cref="PdfWatermarkEngine"/> (прогон), <see cref="WatermarkStamp"/> (знак),
/// <see cref="IssueJournal"/> (журнал) и <see cref="PdfWatermarkWindow"/> (окно).
///
/// Свободный текст работает без базы; выдача учтенной копии дополнительно пишет строку в
/// готовую коллекцию, поэтому перед записью проверяется ее структура.
/// </summary>
public sealed class PdfWatermarkExtension : IExtension
{
    public const string ExtensionId = "pdf-watermark";

    /// <summary>Текст предупреждения на знаке. Ведет само окно — там его и правят; настройка
    /// держит последнее значение и дает посмотреть или очистить его.</summary>
    public const string WarningKey = "warning";

    /// <summary>Папка для сохранения результата. Ведет само окно, но она стабильна и живет
    /// между запусками.</summary>
    public const string OutputKey = "output";

    /// <summary>Имя базы, где лежит журнал выдачи. Ведет само окно.</summary>
    public const string DatabaseKey = "database";

    /// <summary>Имя коллекции журнала выдачи. Ведет само окно.</summary>
    public const string CollectionKey = "collection";

    /// <summary>Что пишется на знаке, если настройка пуста.</summary>
    public const string DefaultWarning = "Передача третьим лицам запрещена";

    public string Id   => ExtensionId;
    public string Name => "Водяной знак на PDF";

    public string MarkdownDescription =>
        """
        Накладывает на каждую страницу PDF компактный диагональный водяной знак. Можно ввести
        свободный текст или выдать учтенную копию с номером экземпляра и записью в таблицу.
        Подходит для текстовых документов, сканов и чертежей.

        ## Два режима

        **«Свободный текст»** — многострочное поле для произвольной надписи. Например:

        ```
        Для внутреннего использования
        Отдел разработки
        Передача третьим лицам запрещена
        ```

        Печатается введенный текст. База данных, коллекция, получатель и дата выдачи для этого
        режима не нужны. Текст используется только в текущем окне и в выходном PDF: в настройки,
        таблицы и журнал приложения он не записывается.

        **«С записью в таблицу»** — выдача копии с автоматическим номером экземпляра. Поле
        **«Выдан»**, дата и предупреждение формируют надпись:

        ```
        КОПИЯ
        Экземпляр № 3
        Выдан: Иванов Иван Иванович
        Дата выдачи: 09.11.2026
        Передача третьим лицам
        запрещена
        ```

        Номер и дата в примере условные. Каждый документ получает свой фактический номер, а
        предупреждение можно изменить в окне. На документ создается одна строка журнала выдачи.

        ## Вид и размещение

        Шрифт узкий полужирный, «КОПИЯ» крупнее остальных строк. Надпись светлая полупрозрачная,
        с контуром букв. Длинные строки переносятся внутри блока, все строки выровнены по центру.
        **Весь блок целиком повернут по диагонали снизу слева вверх направо.**

        Размещение выбирается отдельно от режима текста:

        - **«По центру»** — один диагональный блок в центре каждой страницы.
        - **«Блоками по всей странице»** — повторение целого блока диагональными рядами, с
          промежутками между соседними надписями.

        В разделе **«Границы блока и отступы, мм»** задаются **«Ширина блока»**, **«Высота
        блока»** и **«Отступ от краев»**. Размеры блока задаются до поворота. Для повторения
        доступны **«Промежуток между столбцами»** и **«Промежуток между рядами»**. Границы
        ограничивают область текста; размещение учитывает повернутые габариты блока.

        ## Перед первым запуском с записью в таблицу

        Подготовьте обычную коллекцию журнала выдачи. Расширение ее не создает. Требуются ровно
        четыре столбца в таком порядке:

        | № | Столбец | Тип | Что попадает |
        |---|---|---|---|
        | 1 | Документ | системный столбец записи — переименуйте «Название» | имя файла без расширения |
        | 2 | Экземпляр | Число | выданный номер |
        | 3 | Кому выдан | Текст | значение поля «Выдан» |
        | 4 | Дата выдачи | Дата | дата из окна, без времени |

        У столбца **«Дата выдачи»** выключите **«Отображать в календаре»**, чтобы выдачи не
        становились событиями календаря. Неподходящая структура блокирует запуск: окно объясняет,
        какой столбец исправить. Для записи нужны права создания и изменения записей журнала.

        Название поля в окне — **«Выдан»**; имя столбца существующего журнала остается
        **«Кому выдан»**. Переименовывать его не требуется.

        Номер экземпляра уникален в пределах документа, который определяется именем PDF без
        расширения. Выбирается первый свободный номер: заняты 1 и 3 — выдается 2. Номер вводить
        вручную не нужно. Один документ можно выдавать одному получателю несколько раз.

        ## Как пользоваться

        1. Выберите режим надписи.
        2. Нажмите **«Файл…»** или **«Папка…»** и выберите исходные PDF. Для папки при
           необходимости включите **«Рекурсивный поиск»**.
        3. Укажите **папку для сохранения результата**.
        4. В свободном режиме введите текст. В режиме с таблицей заполните **«Выдан»**,
           проверьте **дату выдачи**, **текст предупреждения**, **базу данных** и **коллекцию
           журнала выдачи**.
        5. Выберите размещение и задайте размеры блока, промежутки и отступы.
        6. Нажмите **«Запустить»**. Прогресс и результат по каждому файлу появятся в окне.
           **«Остановить»** прекращает дальнейшую обработку и сохраняет уже готовые копии.

        ## Что получится

        В свободном режиме — файл `<имя документа> водяной знак.pdf`. В режиме с таблицей —
        `<имя документа> экз. N.pdf` и строка журнала с документом, номером, получателем и датой.
        Если имя результата занято, добавляется счетчик, например `… экз. 3 (2).pdf`.
        **Исходные документы остаются без изменений.**

        Повторение надписи на страницах не создает дополнительных выдач: один обработанный
        документ — один экземпляр и одна строка журнала. Номер резервируется перед нанесением
        знака; при сбое обработки резерв снимается. Если снять его не удалось, окно прямо
        сообщает о занятом номере.

        Защищенные паролем и поврежденные PDF пропускаются с объяснением; обработка остальных
        продолжается. Остановка сохраняет уже завершенные файлы и их записи выдачи.

        ## Что запоминается

        Четыре настройки расширения — **«Текст предупреждения на знаке»**, **«Папка для
        сохранения результата»**, **«База данных журнала»**, **«Коллекция журнала выдачи»** —
        ведет само окно. Предупреждение запоминается при запуске с записью в таблицу; пустая
        настройка означает «Передача третьим лицам запрещена». База и коллекция запоминаются,
        когда структура журнала подходит. Получатель и свободный текст настройками не являются.

        ## Знак становится частью изображения

        Страница переводится в изображение, и надпись впечатывается в его пиксели. Результат
        сохраняется как PDF. Знак нельзя выбрать и удалить как отдельный текстовый объект или
        слой. Контур букв затрудняет удаление осветлением изображения.

        Полной защиты от ручной ретуши, печати или пересъемки экрана это не дает. Журнал выдачи
        в режиме с таблицей сохраняет сведения о том, кому выдан экземпляр.

        У выходного PDF отсутствует текстовый слой: для поиска и выделения текста потребуется
        OCR. Пропадают закладки и ссылки, векторный чертеж становится изображением, электронная
        подпись исходного PDF не сохраняет силу. Эти изменения касаются выходной копии.

        Документ в журнале узнается по имени: переименование строки может освободить ранее
        выданный номер. Исправляйте такие записи с учетом уже выданных копий.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    /// <summary>
    /// Четыре поля, которые ведет само окно. Показаны они здесь затем, чтобы их было видно и
    /// можно было очистить или задать заранее на новой машине.
    ///
    /// ФИО получателя настройкой сознательно НЕ объявлено, в отличие от «Регистрации КД»: там
    /// ФИО принадлежит машине и меняется редко, здесь получатель меняется на каждую выдачу, и
    /// подставлять чужую фамилию из настроек нельзя.
    /// </summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(WarningKey,    "Текст предупреждения на знаке", DefaultWarning),
        new(OutputKey,     "Папка для сохранения результата", "Куда класть документы со знаком"),
        new(DatabaseKey,   "База данных журнала",           "Имя базы из списка баз"),
        new(CollectionKey, "Коллекция журнала выдачи",      "Журнал выдачи"),
    ];

    public Window? CreateWindow() => new PdfWatermarkWindow();

    /// <summary>Текст предупреждения: пусто в настройках — значение по умолчанию. Знак без
    /// предупреждения смысл теряет, поэтому пустым он не остается.</summary>
    public static string Warning(string? raw) =>
        (raw ?? "").Trim() is { Length: > 0 } text ? text : DefaultWarning;
}
