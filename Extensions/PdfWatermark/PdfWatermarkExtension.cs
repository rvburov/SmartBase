using Avalonia.Controls;

namespace SmartBase.Extensions.PdfWatermark;

/// <summary>
/// Контракт расширения «Водяной знак на PDF»: имя, описание и настройки. Вся работа — в
/// <see cref="PdfWatermarkEngine"/> (прогон), <see cref="WatermarkStamp"/> (знак),
/// <see cref="IssueJournal"/> (журнал) и <see cref="PdfWatermarkWindow"/> (окно).
///
/// От соседей отличается тем, что делает две вещи сразу: создает файлы на диске И пишет в чужую
/// готовую коллекцию. Отсюда и проверка структуры выбранной коллекции — как у «Регистрации КД».
/// </summary>
public sealed class PdfWatermarkExtension : IExtension
{
    public const string ExtensionId = "pdf-watermark";

    /// <summary>Текст предупреждения на знаке. Ведет само окно — там его и правят; настройка
    /// держит последнее значение и дает посмотреть или очистить его.</summary>
    public const string WarningKey = "warning";

    /// <summary>Папка для сохранения результата. Ведет само окно, но она стабильна и живет
    /// между запусками.</summary>
    public const string OutputKey = "output";

    /// <summary>Имя базы, где лежит журнал выдачи. Ведет само окно.</summary>
    public const string DatabaseKey = "database";

    /// <summary>Имя коллекции журнала выдачи. Ведет само окно.</summary>
    public const string CollectionKey = "collection";

    /// <summary>Что пишется на знаке, если настройка пуста.</summary>
    public const string DefaultWarning = "Передача третьим лицам запрещена";

    public string Id   => ExtensionId;
    public string Name => "Водяной знак на PDF";

    public string MarkdownDescription =>
        """
        Накладывает на PDF диагональную надпись «кому выдан, какой экземпляр, когда» и заводит
        строку в журнале выдачи — обычной коллекции программы. Потом по этой строке видно, чей
        экземпляр всплыл на стороне.

        Годится любой PDF: чертеж из САПР, скан-картинка, текстовый документ. Содержимое
        страницы не разбирается — надпись ложится поверх.

        ## Что делает

        ### Знак

        Три строки по диагонали листа, снизу вверх, серым полупрозрачным — поверх содержимого, на
        каждой странице документа:

        ```
        Выдан: Иванов Иван Иванович
        Экз. № 3 · 29.08.2026
        Передача третьим лицам запрещена
        ```

        Серый и полупрозрачный, чтобы документ под знаком читался целиком. Три строки, а не одна:
        кегль подбирается так, чтобы блок занял диагональ листа, — разбитая надпись садится на тот
        же лист буквами втрое крупнее и заметно крупнее текста самого документа.

        Знак подгоняется под каждую страницу отдельно, поэтому в документе со смешанными
        форматами выглядит везде одинаково: на листе большего формата он просто крупнее.

        ### Знак нельзя стереть редактором

        Каждая страница переводится в изображение, и надпись рисуется прямо по его пикселям —
        знак становится частью самой страницы, а не отдельным слоем поверх нее. Выделить его,
        выбрать и удалить, как обычный текст, невозможно: удалять нечего. У букв знака есть еще и
        контур, поэтому не помогает и осветление картинки — оно съедает вместе со знаком сам
        документ.

        Совсем неуничтожимым знак не бывает: пиксели можно закрасить в графическом редакторе
        вручную. Но эта работа идет по тем же местам, где лежит текст документа, следы видны, и
        пакетно на десятки файлов она уже не делается. А со стертым знаком остается запись в
        журнале выдачи — по ней все равно видно, кому ушел экземпляр.

        ### Номер экземпляра

        Уникален в пределах ДОКУМЕНТА, а документ — это имя файла без расширения. Первый
        свободный: заняты 1 и 3 — выдается 2. У каждого документа нумерация своя, поэтому
        занятый первый экземпляр сборочного чертежа не мешает выдать первый экземпляр
        спецификации.

        Один и тот же документ можно выдать одному и тому же человеку сколько угодно раз — это
        не дубль, экземпляры различаются номером и датой.

        Вводить номер в окне не нужно и негде: он подбирается сам, в момент записи. Если
        понадобится поправить выданный номер, это делается прямо в коллекции журнала — там
        обычная ячейка.

        ## Перед первым запуском

        ### Настройки расширения

        Четыре поля в разделе **Настройки → Расширения** — **Текст предупреждения на знаке**,
        **Папка для сохранения результата**, **База данных журнала** и **Коллекция журнала
        выдачи**. Заполнять их руками не надо: их ведет само окно. Выбрали один раз — дальше
        подставляются сами.

        Видны они в настройках затем, чтобы их можно было посмотреть, очистить или задать
        заранее на новой машине.

        Текст предупреждения по умолчанию — «Передача третьим лицам запрещена»; правится он
        прямо в окне под конкретную выдачу и запоминается на следующий раз. Это третья строка
        знака и самая длинная: чем она длиннее, тем мельче весь знак.

        ФИО получателя настройкой сознательно не сделано — получатель меняется на каждую выдачу,
        и подставлять чужую фамилию нельзя.

        > Запоминается только выбор, на котором можно работать: если у коллекции не та
        > структура, она в настройки не запишется.

        ### Журнал выдачи

        Это обычная коллекция программы, которую вы заводите сами — расширение ее не создает, а
        только дописывает в нее строки. Столбцов должно быть ровно четыре и ровно в таком
        порядке:

        | № | Столбец | Тип | Что попадает |
        |---|---|---|---|
        | 1 | Документ | системный столбец записи — переименуйте «Название» | имя файла без расширения |
        | 2 | Экземпляр | Число | выданный номер |
        | 3 | Кому выдан | Текст | введенное ФИО |
        | 4 | Дата выдачи | Дата | дата из окна, без времени |

        > У столбца **«Дата выдачи»** выключите тумблер **«Отображать в календаре»** — программа
        > включает его новому столбцу-дате сама. Если оставить включенным, каждая выдача станет
        > событием календаря, и раздел «Календарь» заполнится сотнями «выдач». Расширение такую
        > коллекцию не примет и прямо об этом скажет.

        Коллекция с другим набором, порядком или типом столбцов отклоняется с сообщением
        **«Вы выбрали неправильную коллекцию»**, и окно называет, что именно не на месте. Кнопка
        «Запустить» при этом остается выключенной — записать что-то не туда нельзя.

        Регистр букв и лишние пробелы в названиях столбцов расширение прощает, а вот порядок —
        нет: переставленные столбцы означают, что значения легли бы не туда.

        ## Как пользоваться

        1. Выберите **файл** или **папку** с документами — для этого две отдельные кнопки,
           «Файл…» и «Папка…». Для папки можно включить **«Рекурсивный поиск»**: тогда обойдутся
           и все вложенные папки.
        2. Укажите **папку для сохранения результата** — туда лягут документы со знаком.
        3. Впишите **ФИО, кому выдан** документ, и проверьте **дату выдачи** — по умолчанию она
           сегодняшняя.
        4. При необходимости поправьте **текст предупреждения** — он попадет на знак третьей
           строкой.
        5. Выберите **базу данных** и **коллекцию** журнала. В следующий раз этот шаг можно
           пропустить — выбор запомнится.
        6. Нажмите **«Запустить»**. Ход работы виден в журнале окна, прервать прогон можно
           кнопкой «Остановить».

        ## Что получится

        **Файл** `<имя документа> экз. N.pdf` в папке для результата — на каждый выданный
        документ свой. Если файл с таким именем там уже лежит, к имени приписывается счетчик:
        `… экз. 3 (2).pdf`.

        **Строка в журнале выдачи** — документ, номер экземпляра, получатель и дата.

        **Исходные документы не изменяются**: расширение складывает результат отдельными
        файлами и к оригиналам не прикасается.

        При выборе папки номер подбирается **каждому файлу по своему документу**, поэтому три
        разных документа получат по первому экземпляру, а два файла с одинаковым именем в разных
        подпапках — первый и второй экземпляр одного документа.

        ## Особенности

        ### Чем платим за несмываемый знак

        - **Текстового слоя в выданном документе не остается.** Поиск по словам и выделение
          текста работать не будут, пропадают закладки и ссылки, а векторный чертеж становится
          картинкой и перестает масштабироваться без потери качества.
        - **Электронная подпись становится недействительной**: файл пересобирается целиком. Это
          свойство работы с PDF, а не сбой — подписывайте документы заново после наложения знака.

        Все перечисленное касается только выданной копии: исходный документ остается прежним.

        ### Чего расширение не делает

        - **Не мешает распечатать документ или переснять экран.** Никакая программа этого не
          запретит: знак делает утечку именной, а не невозможной.
        - **Не сторожит переименование в журнале.** Документ узнается по имени, поэтому если
          поправить название строки, ее номер освободится и выдастся кому-то повторно.
        - **Не разбирает защищенные паролем и поврежденные файлы** — они пропускаются со строкой
          в журнале окна, а пачка идет дальше.

        ### Прочее

        - **Окно остается открытым**: получатель, дата, база и коллекция сохраняются для
          следующей выдачи — выдавать пачкой удобно.
        - **Остановка оставляет сделанное как есть.** Уже обработанные файлы лежат в папке
          результата, их номера записаны в журнал — по ним могли уже отдать бумагу.
        - **Большие пачки идут ровно**: 20 000 документов — около четверти часа, и последний файл
          обрабатывается с той же скоростью, что и первый.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    /// <summary>
    /// Четыре поля, которые ведет само окно. Показаны они здесь затем, чтобы их было видно и
    /// можно было очистить или задать заранее на новой машине.
    ///
    /// ФИО получателя настройкой сознательно НЕ объявлено, в отличие от «Регистрации КД»: там
    /// ФИО принадлежит машине и меняется редко, здесь получатель меняется на каждую выдачу, и
    /// подставлять чужую фамилию из настроек нельзя.
    /// </summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(WarningKey,    "Текст предупреждения на знаке", DefaultWarning),
        new(OutputKey,     "Папка для сохранения результата", "Куда класть документы со знаком"),
        new(DatabaseKey,   "База данных журнала",           "Имя базы из списка баз"),
        new(CollectionKey, "Коллекция журнала выдачи",      "Журнал выдачи"),
    ];

    public Window? CreateWindow() => new PdfWatermarkWindow();

    /// <summary>Текст предупреждения: пусто в настройках — значение по умолчанию. Знак без
    /// предупреждения смысл теряет, поэтому пустым он не остается.</summary>
    public static string Warning(string? raw) =>
        (raw ?? "").Trim() is { Length: > 0 } text ? text : DefaultWarning;
}
