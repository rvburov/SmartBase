using Avalonia.Controls;

namespace DataBase.Extensions.PdfAnalyzer;

/// <summary>
/// Расширение «Анализ PDF файлов»: по папке с PDF формирует Excel-отчёт (ведомости/опись КД/ТД)
/// с разбором обозначений по ГОСТ, MD5, числом и форматами листов. Запускается отдельным окном
/// (<see cref="PdfAnalyzerWindow"/>) в основном стиле приложения. Логика — в
/// <see cref="PdfAnalyzerEngine"/> и <see cref="DocumentCodes"/>; зависит от PdfPig (чтение PDF)
/// и ClosedXML (Excel).
/// </summary>
public sealed class PdfAnalyzerExtension : IExtension
{
    public string Id   => "pdf-analyzer";
    public string Name => "Анализ PDF файлов";

    public string MarkdownDescription =>
        """
        Анализирует папку с PDF-файлами и формирует Excel-отчёт по документам: ведомости и
        опись конструкторской/технологической документации.

        **Что делает**
        - Разбирает имя файла: извлекает номера КД/ПД/ТД по ГОСТ 2.201 / 19.101 и название.
        - Считает MD5, число страниц и **форматы листов** по размерам страниц
          (A0–A4 и производные, допуск 30 мм), «листов формата А4», объём.
        - Формирует наименование документа из справочника кодов + спецификаций.

        **Типы выгрузки**
        - Ведомость технологической документации (ТД)
        - Ведомость конструкторской документации (КД/ПД)
        - Опись конструкторской документации (сокращённый формат)
        - Все данные

        **Порядок строк**
        - Рекурсивный поиск — группировка по папкам, внутри по коду документа КД.
        - Без рекурсии — текущая папка, по имени файла А→Я.
        - Сохранить порядок из папки — текущая папка, по дате изменения (старые→новые).

        > Отчёт сохраняется в .xlsx (лист «ОПИСЬ»), со стилем (Times New Roman, границы, ширины колонок).
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new PdfAnalyzerWindow();
}
