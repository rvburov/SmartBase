using Avalonia.Controls;

namespace SmartBase.Extensions.PdfAnalyzer;

/// <summary>
/// Расширение «Анализ PDF файлов»: по папке с PDF формирует Excel-отчет (ведомости/опись КД/ТД)
/// с разбором обозначений по ГОСТ, MD5, числом и форматами листов. Запускается отдельным окном
/// (<see cref="PdfAnalyzerWindow"/>) в основном стиле приложения. Логика — в
/// <see cref="PdfAnalyzerEngine"/> и <see cref="DocumentCodes"/>; зависит от PdfPig (чтение PDF)
/// и ClosedXML (Excel).
/// </summary>
public sealed class PdfAnalyzerExtension : IExtension
{
    public string Id   => "pdf-analyzer";
    public string Name => "Анализ PDF файлов";

    public string MarkdownDescription =>
        """
        Обходит папку с PDF-файлами и собирает по ним Excel-отчет — ведомость или опись
        документации. Обозначения, наименования, число листов и форматы берутся из самих
        файлов, вручную ничего перебивать не нужно.

        ## Что делает

        - **Разбирает имя файла**: извлекает децимальные номера КД, ПД и ТД по
          ГОСТ 2.201 / 19.101 / 19.103 и название документа.
        - **Читает сам PDF**: число страниц, размеры каждой страницы, MD5 файла.
        - **Определяет форматы листов** по размерам страниц — A0…A4 и производные, с
          допуском 30 мм на отклонения печати, — и пересчитывает объем в «листах формата А4».
        - **Собирает наименование документа** по справочнику кодов и спецификаций. Для
          программной документации тип берется по коду вида документа (ГОСТ 19.101), а
          обозначение без кода вида читается как сама программа.

        Содержимое чертежа не разбирается: расширение смотрит только на имя файла и на
        геометрию страниц. Значит, **имя файла должно быть по ГОСТ** — иначе документ попадет
        в отчет без разобранного обозначения.

        ## Перед первым запуском

        Настраивать нечего: у расширения нет ни одного поля в разделе
        **Настройки → Расширения**. Достаточно папки с документами и папки, куда положить
        отчет.

        ## Как пользоваться

        1. Укажите **папку с PDF-файлами**.
        2. Выберите **тип выгрузки** — от него зависит и набор строк, и набор колонок
           (таблица ниже).
        3. При необходимости включите **«Рекурсивный поиск»** — тогда обойдутся и все
           вложенные папки.
        4. Решите, нужно ли **«Сохранить порядок файлов из папки»**. Эта галочка и рекурсия
           взаимно исключают друг друга: порядок из папки имеет смысл только в пределах
           одной папки.
        5. Галочка **«Наименование документа в несколько строк»** включена по умолчанию: она
           разносит изделие, тип и лист по строкам внутри ячейки. Снимите ее, если
           наименование должно идти одной строкой.
        6. Укажите **папку для сохранения результата** и нажмите **«Запустить»**.

        ### Типы выгрузки

        | Тип | Что попадет |
        |---|---|
        | Ведомость технологической документации | только ТД |
        | Ведомость конструкторской документации | только КД |
        | Ведомость программной документации | только ПД |
        | Опись конструкторской документации | только КД, сокращенный набор колонок |
        | Опись программной документации | только ПД, сокращенный набор колонок |
        | Все данные | все найденное, все колонки |

        ### Порядок строк в отчете

        | Что выбрано | Как отсортировано |
        |---|---|
        | Рекурсивный поиск | по папкам, внутри папки — по коду документа КД |
        | Ни то, ни другое | текущая папка, по имени файла А→Я |
        | Сохранить порядок из папки | текущая папка, по дате изменения (старые → новые) |

        ## Что получится

        Файл **`pdf_info.xlsx`** в выбранной папке: один лист **«ОПИСЬ»**, стиль
        Times New Roman с границами и подобранными ширинами колонок. Высота строк
        подгоняется под многострочные наименования.

        Исходные PDF не изменяются и никуда не копируются — расширение только читает их.

        По окончании окно покажет статистику прогона и предложит открыть папку с отчетом.

        ## Особенности

        - **Имя отчета всегда одно и то же.** Повторный прогон в ту же папку затирает
          прошлый `pdf_info.xlsx` — переименуйте его или выберите другую папку, если нужны
          оба.
        - **Файлы с именем не по ГОСТ в отчет попадают**, но обозначение и наименование у
          них разобрать не из чего: колонки останутся пустыми. По ним и видно, что
          переименовать.
        - **Формат листа определяется по размеру страницы**, а не по штампу: страница,
          обрезанная или собранная не в тот формат, будет названа тем форматом, на который
          похожа по размерам.
        - Долгий прогон идет по файлам с показом прогресса; чтение PDF упирается в скорость
          диска или сети.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new PdfAnalyzerWindow();
}
