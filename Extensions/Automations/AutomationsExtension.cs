using Avalonia.Controls;

namespace SmartBase.Extensions.Automations;

/// <summary>
/// Расширение «Автоматизации» — хозяин над маленькими автоматизациями сценариев
/// (docs/ROADMAP-API.md, шаг 13).
///
/// <b>Оно отвечает на вопрос «а можно писать скрипты?».</b> Нельзя: песочницы в .NET нет, и
/// отдельный интерпретатор в приложении не используется. Автоматизация описывается одним
/// файла: новый класс, реализующий <see cref="IAutomation"/>, сам появляется в списке шагов
/// сценария — реестр находит его по сборке (<see cref="AutomationRegistry"/>).
///
/// Своего окна у расширения нет, и это не заготовка на будущее: делать автоматизациям в окне
/// нечего — они живут шагами сценария, а настраиваются там же, где шаг.
///
/// Кроме самих автоматизаций расширение дает одно готовое действие — сборку книги Excel из
/// строк (<see cref="SheetAction"/>): выгрузка в книгу нужна почти каждому обмену, а писать ее
/// в каждой автоматизации заново значило бы десять раз повторить один и тот же код.
/// </summary>
public sealed class AutomationsExtension : IExtension
{
    public const string ExtensionId = "automations";

    public string Id   => ExtensionId;
    public string Name => "Автоматизации";

    public string MarkdownDescription =>
        """
        Маленькие пересчеты для сценариев обмена: строки пришли — строки ушли. Свести выгрузку
        по проектам, сложить трудоемкость по исполнителям, собрать книгу Excel из того, что
        принес предыдущий шаг.

        Своего окна у расширения нет. Все, что оно умеет, ставится **шагом сценария**:
        «Настройки → Интеграции → Сценарии», кнопка «+ Действие».

        ## Что делает

        Каждая автоматизация — отдельный пункт в списке действий. Ей достаются строки, которые
        принес предыдущий шаг (ответ сторонней программы, разобранное сообщение из папки обмена,
        события календаря), и настройки, заданные в самом шаге. Обратно она отдает строки —
        дальше по сценарию их можно отобрать, разложить по полям записи или выгрузить в файл.

        Готовых пунктов два:

        - **Свести строки по ключу** — одна строка на каждое значение ключевой колонки: сколько
          строк было и сумма числовой колонки, если она названа.
        - **Выгрузить строки в книгу Excel** — строки становятся листом книги; файл кладет сама
          программа в выбранную папку.

        ## Перед первым запуском

        Настраивать нечего. Все настройки задаются в шаге сценария — там же, где выбирается
        само действие.

        ## Как пользоваться

        1. Откройте «Настройки → Интеграции → Сценарии» и заведите или откройте сценарий.
        2. Поставьте перед этим шагом тот, который приносит строки: «запрос в коллекцию» или
           «файл из папки».
        3. Нажмите «+ Действие», выберите нужный пункт расширения «Автоматизации».
        4. Заполните настройки: имя ключевой колонки, имя листа, папку для файла.
        5. Сохраните сценарий и нажмите «Запустить» — отчет покажет, сколько строк получилось.

        ## Что получится

        Строки, пересчитанные так, как просит автоматизация, — их видно в отчете о запуске и
        ими работают следующие шаги. У выгрузки в книгу получается файл `.xlsx` в выбранной
        папке; к имени добавляется момент выгрузки, так что вчерашний файл не пропадет под
        сегодняшним.

        ## Особенности

        - **В базу автоматизация не пишет и в сеть не ходит.** Ей доступны только строки шага и
          его настройки.
        - **Файл кладет программа, а не расширение.** Папка задается в настройках шага.
        - **Строк за один запуск — не больше 500.** Столько сценарий передает между шагами.
        - **Пустой ответ — не ошибка.** Если после свода не осталось ни одной строки, сценарий
          спокойно кончается на этом шаге.
        """;

    /// <summary>
    /// Окна нет: автоматизации живут шагами сценария. Кнопка «Запустить» поэтому и не горит —
    /// нажимать было бы не на что.
    /// </summary>
    public bool CanRun => false;

    public Window? CreateWindow() => null;

    /// <summary>
    /// Что можно поставить шагом: все найденные автоматизации плюс сборка книги Excel. Список
    /// собирается ОДИН раз — реестр автоматизаций ленивый, и перебирать типы сборки на каждую
    /// перерисовку окна сценария незачем.
    /// </summary>
    public IReadOnlyList<IExtensionAction> Actions { get; } =
    [
        .. AutomationRegistry.All.Select(IExtensionAction (a) => new AutomationAction(a)),
        new SheetAction(),
    ];
}
