using Avalonia.Controls;

namespace SmartBase.Extensions.ProductCompare;

/// <summary>
/// Расширение «Сравнение составов изделий»: сравнивает два Excel-состава (старый/новый) и
/// формирует итог в .xlsm-шаблоне. Запускается отдельным окном (<see cref="ProductCompareWindow"/>)
/// в основном стиле приложения. Логика вынесена в <see cref="ProductCompareEngine"/>; расширение
/// самостоятельно и зависит только от <see cref="IExtension"/> + контролов/стилей приложения.
/// </summary>
public sealed class ProductCompareExtension : IExtension
{
    /// <summary>Идентификатор строкой-константой — на него ссылается окно, когда читает
    /// свои настройки у оболочки.</summary>
    public const string ExtensionId = "product-compare";

    /// <summary>Имя настройки «файл-шаблон» (полный ключ хранения собирает оболочка).</summary>
    public const string TemplateKey = "template";

    public string Id   => ExtensionId;
    public string Name => "Сравнение составов изделий";

    /// <summary>Путь к шаблону в коде не зашит: файл лежит на файловом сервере, буква
    /// смонтированного диска у каждой машины своя.</summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(TemplateKey, "Файл-шаблон", @"\\server\share\Шаблон сравнения файлов изделий.xlsm"),
    ];

    public string MarkdownDescription =>
        """
        Сравнивает составы одного изделия из двух Excel-файлов — прежнего и нового — и
        показывает в одном листе, что удалено, что добавлено, а что осталось на месте.
        Нужно, когда состав изделия пересматривали и требуется перечень изменений.

        ## Что делает

        - Сопоставляет строки двух файлов по **иерархическому номеру** (столбец 2), а
          уникальность строки определяет по **обозначению** (столбец 11).
        - Пишет в шаблон старые данные слева (столбцы 1–5), новые — справа (столбцы 7–11),
          начиная с 6-й строки: строки-ровесники встают друг напротив друга.
        - Подсвечивает **красным** то, что есть только в старом файле (удалено), и
          **зеленым** то, что есть только в новом (добавлено). Не подсвеченное — общее.
        - Применяет стиль ГОСТ (шрифт «GOST type A», границы, выравнивание); макросы
          шаблона сохраняются.

        Читается **первый лист** каждого файла — не тот, что был открыт последним, а именно
        первый по порядку.

        ## Перед первым запуском

        Нужен **файл-шаблон** — готовая книга `.xlsm` с макросами, в которую записывается
        результат. Расширение его не создает: шаблон лежит у предприятия, обычно в общей
        сетевой папке. Спросите его у того, кто ведет составы изделий.

        Путь к шаблону — единственная настройка расширения (**Настройки → Расширения**,
        поле «Файл-шаблон»). Заранее ее заполнять не нужно: укажите шаблон кнопкой «Обзор»
        в самом окне, и путь запомнится — при следующем открытии он подставится сам. Поле в
        настройках нужно, чтобы посмотреть сохраненный путь, поправить его или очистить.

        Кнопка «Запустить» включается, только когда указаны все четыре пути — шаблон, оба
        файла и папка результата.

        ## Как пользоваться

        1. Укажите **файл-шаблон** (.xlsm) — если он запомнен, поле уже заполнено.
        2. Укажите **старый файл** состава (.xlsx или .xlsm).
        3. Укажите **новый файл** состава.
        4. Выберите **папку для сохранения результата**.
        5. Нажмите **«Запустить»**. По окончании расширение предложит открыть папку с
           результатом.

        ## Что получится

        Новый файл **«Результат сравнения ДД.ММ.ГГГГ_ЧЧ-ММ-СС.xlsm»** в выбранной папке.
        Исходные файлы и сам шаблон не изменяются — результат всегда пишется отдельной
        книгой, шаблон только копируется.

        ## Особенности

        - **Имя файла содержит секунды**, поэтому прогоны не затирают друг друга: сравнивать
          можно сколько угодно раз подряд.
        - **Файл-шаблон заранее не проверяется.** Сетевая папка может быть временно
          недоступна, и блокировать из-за этого окно незачем: если к моменту запуска шаблона
          на месте нет, расширение скажет «Файл-шаблон не найден».
        - **Строка без обозначения** в сравнении не участвует как уникальная: сопоставление
          идет по иерархическому номеру, а уникальность считается по обозначению.
        - **Отдельной кнопки остановки нет.** Ход работы виден на индикаторе, а прервать
          прогон можно закрытием окна — на время работы кнопки выбора файлов выключены.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new ProductCompareWindow();
}
