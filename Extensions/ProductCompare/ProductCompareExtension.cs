using Avalonia.Controls;

namespace SmartBase.Extensions.ProductCompare;

/// <summary>
/// Расширение «Сравнение составов изделий» — два режима в одном окне
/// (<see cref="ProductCompareWindow"/>): «заключение» сравнивает два Excel-состава
/// (старый/новый, <see cref="ProductCompareEngine"/>), «расшифровка» — все расшифровки изделия
/// из папки по датам (<see cref="BreakdownCompareEngine"/>). Итог пишется в .xlsm-шаблон своего
/// режима. Расширение самостоятельно и зависит только от <see cref="IExtension"/> +
/// контролов/стилей приложения.
/// </summary>
public sealed class ProductCompareExtension : IExtension
{
    /// <summary>Идентификатор строкой-константой — на него ссылается окно, когда читает
    /// свои настройки у оболочки.</summary>
    public const string ExtensionId = "product-compare";

    /// <summary>Шаблон режима «заключение». Ключ остался от времени, когда режим был один:
    /// под ним в app.db лежит уже сохраненный путь.</summary>
    public const string TemplateKey = "template";

    /// <summary>Шаблон режима «расшифровка».</summary>
    public const string BreakdownTemplateKey = "breakdown-template";

    /// <summary>Папка с файлами расшифровок.</summary>
    public const string BreakdownFolderKey = "breakdown-folder";

    /// <summary>Последний выбранный режим окна — память о выборе, а не настройка: на экран
    /// настроек не выводится.</summary>
    public const string ModeKey = "mode";

    public string Id   => ExtensionId;
    public string Name => "Сравнение составов изделий";

    /// <summary>Пути в коде не зашиты: файлы лежат на файловом сервере, буква смонтированного
    /// диска у каждой машины своя.</summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(TemplateKey,          "Файл-шаблон заключения",  @"\\server\share\Шаблон сравнения файлов изделий.xlsm"),
        new(BreakdownTemplateKey, "Файл-шаблон расшифровки", @"\\server\share\Шаблон сравнения расшифровок.xlsm"),
        new(BreakdownFolderKey,   "Папка с расшифровками",   @"\\server\share\Расшифровки изделия"),
    ];

    public string MarkdownDescription =>
        """
        Сравнивает составы одного изделия из файлов Excel. Режимов два: **заключение** —
        прежний и новый состав рядом, удаленное и добавленное подсвечено; **расшифровка** —
        все расшифровки изделия из папки по датам, с операциями, чтобы было видно, что и
        когда менялось.

        ## Что делает

        ### Режим «Сравнение составов изделий заключение»

        - Сопоставляет строки двух файлов по **иерархическому номеру** (столбец 2), а
          уникальность строки определяет по **обозначению** (столбец 11).
        - Пишет в шаблон старые данные слева (столбцы 1–5), новые — справа (столбцы 7–11),
          начиная с 6-й строки: строки-ровесники встают друг напротив друга.
        - Подсвечивает **красным** то, что есть только в старом файле (удалено), и
          **зеленым** то, что есть только в новом (добавлено). Не подсвеченное — общее.
        - Применяет стиль ГОСТ (шрифт «GOST type A», границы, выравнивание); макросы
          шаблона сохраняются.

        Читается **первый лист** каждого файла — не тот, что был открыт последним, а именно
        первый по порядку.

        ### Режим «Сравнение составов изделий расшифровка»

        - Берет из папки все файлы расшифровок (.xlsx, .xlsm) и расставляет их по **дате в
          имени**: имя устроено как «Проект_ГГГГ.ММ.ДД_ФИО», например
          «Изделие АБВГ.000001.001_2026.06.16_Иванова».
        - Проверяет, что все файлы — расшифровки одного изделия: обозначение КД в строке
          «Изделие» должно совпадать.
        - Читает в каждом лист **«Расшифровка»**: изделия вместе с их операциями.
        - Ставит строки изделий всех дат друг напротив друга **по индексу** (столбец
          «Индекс»): «2» напротив «2», «1.1» напротив «1.1», порядок — как у номеров
          (1, 1.1, 1.2, 1.10, 2…). Если изделие вставили или убрали и нумерация
          сдвинулась, напротив друг друга встанут разные изделия — так видно, что на этом
          номере теперь другое. Запись «1.» и «1», «1,2» и «1.2» считается одной.
        - Операции ставит внутри своего изделия (того же индекса) по названию: две
          «Подготовки» — первая к первой, вторая ко второй.
        - Пишет в шаблон по **блоку на дату** слева направо: столбцы A–I, затем K–S,
          U–AC и так далее, от ранней даты к поздней. Шапка повторяется над каждым
          блоком, в заголовке блока (объединенная 1-я строка) — точное имя файла
          расшифровки без расширения. Данные — с 6-й строки, одна строка на изделие или
          операцию для всех дат сразу; если на какую-то дату такой строки не было, клетки ее
          блока пустые.
        - Переносит уровень, индекс, наименование или операцию, обозначение КД или вид
          работ, обозначение ТД, кол-во, Т (1 шт.), Т всего и комментарий — значениями,
          как они видны в файле, и с оформлением файла. Цветом изменения не выделяются.

        ## Перед первым запуском

        У каждого режима свой **файл-шаблон** — готовая книга `.xlsm`, в которую
        записывается результат. Расширение шаблоны не создает: они лежат у предприятия,
        обычно в общей сетевой папке. Спросите их у того, кто ведет составы изделий.

        В **Настройки → Расширения** у расширения три поля: «Файл-шаблон заключения»,
        «Файл-шаблон расшифровки» и «Папка с расшифровками». Заранее их заполнять не нужно:
        укажите файл или папку кнопкой «Обзор» в самом окне, и путь запомнится — при
        следующем открытии он подставится сам. Поля в настройках нужны, чтобы посмотреть
        сохраненный путь, поправить его или очистить.

        Кнопка «Запустить» включается, только когда указаны все пути выбранного режима.

        ## Как пользоваться

        1. В списке **«Режим»** выберите «Сравнение составов изделий заключение» или
           «Сравнение составов изделий расшифровка» — окно запомнит выбор.
        2. Укажите **файл-шаблон** (.xlsm) — если он запомнен, поле уже заполнено.
        3. Для заключения укажите **старый файл** и **новый файл** состава (.xlsx или
           .xlsm). Для расшифровки — **папку с расшифровками**.
        4. Выберите **папку для сохранения результата**.
        5. Нажмите **«Запустить»**. В режиме расшифровки ход работы и найденные файлы видны в
           журнале внизу окна. По окончании расширение предложит открыть папку с
           результатом.

        ## Что получится

        Новый файл в выбранной папке: **«Результат сравнения ДД.ММ.ГГГГ_ЧЧ-ММ-СС.xlsm»** у
        заключения и **«Расшифровка сравнения ДД.ММ.ГГГГ_ЧЧ-ММ-СС.xlsm»** у расшифровки.
        Исходные файлы и сами шаблоны не изменяются — результат всегда пишется отдельной
        книгой, шаблон только копируется. Макросы и все, что есть на листе шаблона
        расшифровки, остаются на своих местах.

        ## Особенности

        - **Имя файла содержит секунды**, поэтому прогоны не затирают друг друга: сравнивать
          можно сколько угодно раз подряд.
        - **Файл-шаблон заранее не проверяется.** Сетевая папка может быть временно
          недоступна, и блокировать из-за этого окно незачем: если к моменту запуска шаблона
          на месте нет, расширение скажет «Файл-шаблон не найден».
        - **Заключение: строка без обозначения** в сравнении не участвует как уникальная:
          сопоставление идет по иерархическому номеру, а уникальность считается по
          обозначению.
        - **Расшифровка не начнется**, если в имени какого-то файла нет даты, если у двух
          файлов одна дата, если файлов меньше двух или если в папке расшифровки разных
          изделий — у них разное обозначение КД в строке «Изделие» листа «Расшифровка». Какие
          файлы мешают — написано в журнале.
        - **Имя файла до даты может быть любым** («ТД …», «ЧАСТНЫЙ СЛУЧАЙ …» и так далее):
          важна только дата. В сравнение идут все файлы папки — лишние уберите из нее до
          запуска.
        - **Расшифровка: подпапки не просматриваются**, а прошлые результаты
          («Расшифровка сравнения …») в сравнение не берутся — сохранять результат можно и в
          папку с расшифровками.
        - **Расшифровка: после вставки или удаления изделия** нумерация ниже сдвигается, и
          напротив одного индекса на разные даты стоят разные изделия — смотрите на
          наименование и обозначение КД в каждом блоке.
        - **Отдельной кнопки остановки нет.** Ход работы виден на индикаторе, а прервать
          прогон можно закрытием окна — на время работы кнопки выбора файлов выключены.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new ProductCompareWindow();
}
