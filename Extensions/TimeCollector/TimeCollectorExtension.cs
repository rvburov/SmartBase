using Avalonia.Controls;

namespace SmartBase.Extensions.TimeCollector;

/// <summary>
/// Расширение «Сводная трудоемкость»: порт макроса <c>TimeCollector</c> из книги
/// «_Таблица трудоемкости.xlsm» (пункт «Обновить» в контекстном меню листа «Таблица»).
/// Обходит папку с файлами расчетов <c>*.xlsm</c>, читает в каждом лист «Расшифровка» и
/// собирает сводную таблицу. Приемников у свода два, выбор — в окне: .xlsm-шаблон на лист
/// «Таблица» (<see cref="TimeSheetWriter"/>) или коллекция программы
/// (<see cref="TimeCollectionWriter"/>).
/// Запускается отдельным окном (<see cref="TimeCollectorWindow"/>) в основном стиле
/// приложения. Логика без UI — в <see cref="TimeCollectorEngine"/>; расширение самостоятельно
/// и зависит только от <see cref="IExtension"/> + контролов/стилей приложения (плюс
/// репозиторий БД для выгрузки в коллекцию — как «Документы в коллекцию»).
/// </summary>
public sealed class TimeCollectorExtension : IExtension
{
    /// <summary>Идентификатор строкой-константой — на него ссылается окно, когда читает
    /// свои настройки у оболочки.</summary>
    public const string ExtensionId = "time-collector";

    /// <summary>Имя настройки «папка с расчетами» (полный ключ хранения собирает оболочка).</summary>
    public const string FolderKey = "folder";

    /// <summary>Имя настройки «файл-шаблон».</summary>
    public const string TemplateKey = "template";

    /// <summary>Имя настройки «папка для результата».</summary>
    public const string OutputKey = "output";

    /// <summary>Имя настройки «файл списка операций» (Операции.xlsx) — для колонок по
    /// операциям в коллекции.</summary>
    public const string OperationsKey = "operations";

    public string Id   => ExtensionId;
    public string Name => "Сводная трудоемкость";

    /// <summary>Пути в коде не зашиты: и расчеты, и шаблон лежат на файловом сервере, а буква
    /// смонтированного диска у каждой машины своя (в макросе папку хранила ячейка
    /// «Настройки»!B1 — здесь ее роль играют эти настройки).</summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(FolderKey,   "Папка с расчетами",    @"\server\share\Расшифровка"),
        new(TemplateKey, "Файл-шаблон",          @"\server\share\_Таблица трудоемкости.xlsm"),
        new(OutputKey,   "Папка для результата", @"D:\Своды"),
        new(OperationsKey, "Файл списка операций", @"\server\share\Расшифровка\Операции.xlsx"),
    ];

    public string MarkdownDescription =>
        """
        Собирает сводную таблицу трудоемкости из папки с файлами расчетов: обходит расчеты,
        читает в каждом лист «Расшифровка» и складывает все строки в один свод. Заменяет
        кнопку «Обновить» в контекстном меню книги «Таблица трудоемкости» — и делает это
        заметно быстрее, потому что расчеты читаются по четыре одновременно.

        Приемников у свода два, и выбирает их список **«Куда выгрузить»** вверху окна:
        **файл Excel по шаблону** или **коллекция в программе**.

        ## Что делает

        - Обходит папку (при желании — с подпапками) и берет файлы `*.xlsm`, имя которых
          подходит под образец `Проект_ГГГГ.ММ.ДД_ФИО.xlsm`.
        - В каждом читает лист «Расшифровка» и берет строки, у которых заполнены и
          «иерархический номер», и «трудоемкость». Первая строка листа — шапка, в свод
          она не попадает.
        - Складывает все в один свод и сортирует: обозначение ↑, дата ↓, наименование ↑.

        ### Колонки свода

        | Колонка | Что попадает |
        |---|---|
        | Наименование | столбец C листа «Расшифровка» |
        | Обозначение КД | столбец D, пробелы удаляются |
        | Тр-ть | столбец G |
        | Дата, ФИО, Проект | разбираются из имени файла расчета |
        | Ссылка (Excel) / Файл расчета (коллекция) | открывает исходный расчет |

        ### Цвета свода

        | Цвет | Что означает |
        |---|---|
        | Желтая / белая строка | Заливка чередуется на каждой смене обозначения КД — видно, где кончается одна группа и начинается следующая. Строка без обозначения — белая. |
        | Красная строка | У одного обозначения совпали проект и дата, а трудоемкость разная. Противоречие: дубль, опечатка или несогласованная правка — нужно разобраться. |
        | Красная ячейка «Тр-ть» | То же расхождение, но проект или дата разные: трудоемкость менялась от проекта к проекту или со временем. Не ошибка, а напоминание, что значение по этой детали не единственное. |

        Красным помечается пара соседних строк — обе участницы расхождения.

        С колонками по операциям (только коллекция) добавляется еще одна пометка:

        | Цвет | Что означает |
        |---|---|
        | Красная ячейка операции | У соседних строк одного обозначения время этой операции разное или операция есть только у одной из них. Если проект или дата разные, это напоминание: разбивка менялась от проекта к проекту или со временем. Если совпадают, стоит проверить расчеты. |

        ### Галочка «Приводить текст к одному алфавиту» (включена)

        Исправляет буквы, набранные не в той раскладке. В кириллице и латинице есть буквы,
        неотличимые на глаз (их называют **гомоглифами**) — `А` и `A`, `О` и `O`, `С` и `C`, —
        и одно обозначение, набранное двумя способами, программа считает двумя разными: в своде
        оно разъезжается на две группы с разной заливкой. Галочка приводит русское слово
        к кириллице, английское — к латинице.

        Решение принимается **по каждому слову отдельно**, поэтому английские слова в русских
        наименованиях не страдают. Слово, о котором решить нельзя, остается как есть. Цифры не
        трогаются никогда. Что исправлено — видно в журнале, обозначения перечисляются поименно.

        Чистятся «Наименование» и «Обозначение КД» — то, что взято из ячеек расчета. «ФИО»
        и «Проект» остаются ровно как в имени файла: по ним макрос шаблона это имя и собирает,
        когда открывает расчет, и исправленная буква оставила бы ссылку без файла.

        ### Галочка «Добавить колонки по операциям» (только коллекция, снята)

        После «Файл расчета» в коллекции появляется по колонке на каждую операцию — как было
        когда-то в книге трудоемкости.

        - В колонке операции — время из столбца G, **на одну штуку изделия**. Берутся только
          собственные операции изделия (строки под ним до следующего изделия), без операций
          составных частей. Одна операция дважды — время складывается.
        - **Колонки дает только список операций** из файла «Операции.xlsx», и они идут в порядке
          этого списка. Создаются лишь те, что встретились в расчетах.
        - **Название сверяется строго**: как написано в списке, так должно быть и в расчете.
          Отличаются только пробелы по краям — их не видно, поэтому они прощаются. Разный
          регистр, лишний пробел внутри или буква из чужой раскладки — это уже другое название.
        - Не нашлось в списке — название ищется в листе «Исправление» того же файла. Если
          правильное название есть в списке, время уходит в его колонку. Если и там нет,
          **значение в коллекцию не попадает**, а журнал называет такое название и число строк:
          видно, что поправить в расчете или дописать в список.
        - У операции **«Сумма операций» колонки нет**: она задает время одной суммой, без
          разбивки. Журнал считает такие строки.
        - Не учитываются пустые строки и операции без числа в G (например, с временем только
          в H — в трудоемкость изделия они тоже не входят). Если время записано текстом, строка
          в колонку не попадет, но журнал назовет расчет.

        Коллекция с операциями **заметно тяжелее** — каждое время хранится отдельным значением,
        и на большом своде объем может вырасти примерно вдвое, — а чтение расчетов дольше.
        Поэтому галочка по умолчанию снята.

        ## Перед первым запуском

        **Расчеты.** Расширение узнает расчет по двум признакам, и оба обязательны: имя файла
        по образцу `Проект_ГГГГ.ММ.ДД_ФИО.xlsm` и лист **«Расшифровка»** внутри. Файл, не
        отвечающий хотя бы одному, в свод не попадет — но и молча не пропадет: он будет назван
        в журнале с причиной.

        **Файл-шаблон** нужен только для выгрузки в Excel — это готовая книга `.xlsm` с листом
        **«Таблица»** и макросами. Расширение его не создает: шаблон лежит у предприятия,
        обычно в общей сетевой папке. Для выгрузки в коллекцию шаблон не нужен вовсе.

        **Файл списка операций** нужен только для колонок по операциям — это книга
        «Операции.xlsx» с листами «Операции» и «Исправление», та же, из которой расчеты берут
        свой список операций.

        **Четыре поля в разделе Настройки → Расширения:**

        | Поле | Что в нем | Откуда берется |
        |---|---|---|
        | Папка с расчетами | путь к папке с файлами `Проект_ГГГГ.ММ.ДД_ФИО.xlsm` | у того, кто ведет расчеты; обычно сетевая папка |
        | Файл-шаблон | путь к книге `.xlsm` с листом «Таблица» | у того, кто ведет книгу трудоемкости |
        | Папка для результата | куда класть готовый свод | ваш выбор, обычно локальная папка |
        | Файл списка операций | путь к книге «Операции.xlsx» | обычно лежит в папке «Расшифровка» рядом с расчетами |

        Заполнять их руками не нужно: укажите папки и файлы кнопками **«Обзор»** прямо в
        окне, и пути запомнятся — при следующем открытии подставятся сами. Поля в настройках
        нужны, чтобы посмотреть сохраненное, поправить его, очистить или задать заранее на
        новой машине.

        Пустое поле ничего не ломает: расширение просто откроется с пустыми путями, и их надо
        будет указать в окне. Путей в коде нет намеренно — буква смонтированного сетевого
        диска у каждой машины своя.

        ## Как пользоваться

        Первые два шага общие: выберите в списке **«Куда выгрузить»** приемник, укажите
        **папку с расчетами** и при необходимости включите **«Рекурсивный поиск»**. Дальше
        поля зависят от приемника.

        ### Выгрузка в файл Excel

        1. Укажите **файл-шаблон** (.xlsm) с листом «Таблица».
        2. Выберите **папку для сохранения результата**.
        3. Нажмите **«Запустить»**.

        ### Выгрузка в коллекцию программы

        1. Выберите **базу данных**, в которой появится коллекция.
        2. При желании задайте **название коллекции**; пустое поле означает имя по умолчанию.
        3. Нужны колонки по операциям — включите **«Добавить колонки по операциям»** и укажите
           **файл списка операций**.
        4. Нажмите **«Запустить»**.

        Ход работы виден на индикаторе: сколько файлов прочитано, какой обрабатывается сейчас
        и сколько примерно осталось. Кнопка **«Остановить»** прерывает прогон в любой момент.

        ## Что получится

        **Файл Excel.** Книга `Трудоемкость (ГГГГ-ММ-ДД_ЧЧ-ММ).xlsm` в выбранной папке. Свод
        пишется на лист «Таблица»: пустые столбцы прячутся, ставятся автофильтр и именованный
        диапазон `ALL_DATA`, макросы шаблона сохраняются. Колонка «Ссылка» (`>>>`) открывает
        исходный расчет на нужной строке.

        Если путь к расчету очень длинный или в имени файла есть скобки, ссылка работает через
        макрос шаблона: такой адрес Excel в формулу не берет. Такие расчеты журнал называет
        **поименно** и с причиной — видно, какой файл переименовать или переложить ближе к
        корню диска.

        Занятое имя файла получает номер — прошлый свод не затирается.

        **Коллекция.** Новая коллекция в выбранной базе с колонками свода: «Наименование» —
        название записи, «Тр-ть» — число, «Дата» — дата, «Файл расчета» — путь к исходному
        расчету, а с галочкой — еще колонки операций. Порядок записей и раскраска строк те же,
        что в Excel-своде, но цветами палитры программы.

        Колонка «Тр-ть» приходит уже настроенной — вид «Число с разрядами», десятичный
        разделитель «запятая», разряды не разделяются, **знаков после запятой — «Авто»**.
        «Авто» значит «сколько есть в расчете»: `12` останется `12`, а `12,456` не округлится.
        Настройки видны и меняются в свойствах колонки.

        Название по умолчанию — «Трудоемкость (ГГГГ-ММ-ДД_ЧЧ-ММ)»; занятое имя тоже получает
        номер, прошлая коллекция остается на месте.

        Каждый прогон — новая коллекция, и на большом своде она весит заметно: около 0,5 ГБ на
        650 тыс. строк. Своды, которые больше не нужны, стоит удалять, а после удаления — сжать
        файл базы: «Настройки → Управление базой данных → Сжать файл» (у общей базы в сетевой
        папке это делает ее администратор; своя база сжимается сама при запуске программы).

        > Строки в коллекции — обычные записи: их можно фильтровать, сортировать, дописывать
        > свои и складывать трудоемкость средствами таблицы.

        Исходные расчеты ни в том, ни в другом случае не изменяются.

        ## Особенности

        ### Журнал: что делать с замечаниями

        Во время прогона журнал молчит — все идет в индикатор, — а по окончании в нем
        появляется разбор файлов, с которыми что-то не так:

        | Секция | Что означает | Что делать |
        |---|---|---|
        | ⚠️ Открыты другим пользователем | книга сейчас открыта в Excel у коллеги (по возможности указано, у кого) | ничего: данные прочитаны с диска, но без правок, которые коллега еще не сохранил |
        | ❌ Не открылись | файл поврежден, заблокирован другой программой или нет прав доступа | проверить файл вручную и повторить прогон |
        | ⏭️ Пропущены | нет листа «Расшифровка», имя не по образцу `Проект_ГГГГ.ММ.ДД_ФИО.xlsm` или нет подходящих строк | переименовать файл или убрать его из папки, если он не расчет |

        Строки непрочитанных и пропущенных файлов в свод **не попали** — по журналу видно,
        чего именно не хватает в результате. Строки файлов, открытых у коллег, в своде есть.

        > Отдельной строкой журнал считает **осиротевшие служебные файлы «~$»**: Excel
        > оставляет их после аварийного закрытия, и они приезжают вместе с копией папки.
        > Замечанием это не считается — книга не открыта, строки собраны полностью. Файлы
        > скрытые, их можно удалить.

        ### Прочее

        - **Все, что расширение хочет сказать, оно говорит в своем журнале**, а не в общей
          диагностике программы: разбирать прогон удобнее там же, где его запускали.
        - **Остановка отменяет результат целиком.** Файл свода не создается, а недособранная
          коллекция удаляется — полурезультата не остается.
        - **Прошлый свод всегда цел.** Результат пишется в новый файл или новую коллекцию,
          поэтому неудачный прогон можно просто повторить — например, со снятой галочкой
          приведения текста к одному алфавиту.
        - Расчеты читаются по четыре одновременно, поэтому сетевая папка обходится заметно
          быстрее, чем из Excel.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new TimeCollectorWindow();
}
