using Avalonia.Controls;

namespace SmartBase.Extensions.TimeCollector;

/// <summary>
/// Расширение «Сводная трудоемкость»: порт макроса <c>TimeCollector</c> из книги
/// «_Таблица трудоемкости.xlsm» (пункт «Обновить» в контекстном меню листа «Таблица»).
/// Обходит папку с файлами расчетов <c>*.xlsm</c>, читает в каждом лист «Расшифровка» и
/// собирает сводную таблицу. Приемников у свода два, выбор — в окне: .xlsm-шаблон на лист
/// «Таблица» (<see cref="TimeSheetWriter"/>) или коллекция программы
/// (<see cref="TimeCollectionWriter"/>).
/// Запускается отдельным окном (<see cref="TimeCollectorWindow"/>) в основном стиле
/// приложения. Логика без UI — в <see cref="TimeCollectorEngine"/>; расширение самостоятельно
/// и зависит только от <see cref="IExtension"/> + контролов/стилей приложения (плюс
/// репозиторий БД для выгрузки в коллекцию — как «Документы в коллекцию»).
/// </summary>
public sealed class TimeCollectorExtension : IExtension
{
    /// <summary>Идентификатор строкой-константой — на него ссылается окно, когда читает
    /// свои настройки у оболочки.</summary>
    public const string ExtensionId = "time-collector";

    /// <summary>Имя настройки «папка с расчетами» (полный ключ хранения собирает оболочка).</summary>
    public const string FolderKey = "folder";

    /// <summary>Имя настройки «файл-шаблон».</summary>
    public const string TemplateKey = "template";

    /// <summary>Имя настройки «папка для результата».</summary>
    public const string OutputKey = "output";

    public string Id   => ExtensionId;
    public string Name => "Сводная трудоемкость";

    /// <summary>Пути в коде не зашиты: и расчеты, и шаблон лежат на файловом сервере, а буква
    /// смонтированного диска у каждой машины своя (в макросе папку хранила ячейка
    /// «Настройки»!B1 — здесь ее роль играют эти настройки).</summary>
    public IReadOnlyList<ExtensionSetting> Settings =>
    [
        new(FolderKey,   "Папка с расчетами",    @"\server\share\Расшифровка"),
        new(TemplateKey, "Файл-шаблон",          @"\server\share\_Таблица трудоемкости.xlsm"),
        new(OutputKey,   "Папка для результата", @"D:\Своды"),
    ];

    public string MarkdownDescription =>
        """
        Собирает сводную таблицу трудоемкости из папки с файлами расчетов. Готовый свод
        выгружается **в файл Excel** по .xlsm-шаблону (замена пункта «Обновить» в контекстном
        меню самой книги) или **в коллекцию программы**. Приемник выбирается в окне списком
        «Куда выгрузить».

        **Что делает**
        - Обходит папку (при желании — с подпапками) и берет файлы `*.xlsm`, имя которых
          подходит под образец `Проект_ГГГГ.ММ.ДД_ФИО.xlsm`.
        - В каждом читает лист «Расшифровка» и берет строки, у которых заполнены и
          «иерархический номер», и «трудоемкость».
        - Складывает все в один свод и сортирует: обозначение ↑, дата ↓, наименование ↑.

        **Колонки свода**

        | Колонка | Что попадает |
        |---|---|
        | Наименование | столбец C листа «Расшифровка» |
        | Обозначение КД | столбец D, пробелы удаляются |
        | Тр-ть | столбец G |
        | Дата, ФИО, Проект | разбираются из имени файла расчета |
        | Ссылка (Excel) / Файл расчета (коллекция) | открывает исходный расчет |

        **Цвета свода**

        | Цвет | Что означает |
        |---|---|
        | Желтая / белая строка | Заливка чередуется на каждой смене обозначения КД — видно, где кончается одна группа и начинается следующая. Строка без обозначения — белая. |
        | Красная строка | У одного обозначения совпали проект и дата, а трудоемкость разная. Противоречие: дубль, опечатка или несогласованная правка — нужно разобраться. |
        | Красная ячейка «Тр-ть» | То же расхождение, но проект или дата разные: трудоемкость менялась от проекта к проекту или со временем. Не ошибка, а напоминание, что значение по этой детали не единственное. |

        Красным помечается пара соседних строк — обе участницы расхождения.

        **Выгрузка в файл Excel**

        1. Укажите папку с расчетами и при необходимости включите «Рекурсивный поиск».
        2. Укажите файл-шаблон (.xlsm) с листом «Таблица».
        3. Выберите папку для результата и нажмите «Запустить».

        Свод пишется на лист «Таблица»: пустые столбцы прячутся, ставятся автофильтр и
        именованный диапазон `ALL_DATA`, макросы шаблона сохраняются. Колонка «Ссылка»
        (`>>>`) открывает исходный расчет на нужной строке — формулой, а у расчетов с очень
        длинным путем (Excel не берет в формулу адрес длиннее 255 знаков) переход делает
        макрос шаблона.

        > Результат сохраняется как «Трудоемкость (ГГГГ-ММ-ДД_ЧЧ-ММ).xlsm»; если такое имя уже
        > занято, к нему добавляется номер — прошлый свод не затирается.

        **Выгрузка в коллекцию программы**

        1. Укажите папку с расчетами и при необходимости включите «Рекурсивный поиск».
        2. Выберите базу данных, в которой появится коллекция.
        3. При желании задайте название коллекции и нажмите «Запустить».

        Создается новая коллекция с колонками свода: «Наименование» — название записи,
        «Тр-ть» — число с двумя знаками после запятой, «Дата» — дата, «Файл расчета» — путь
        к исходному расчету. Порядок записей и раскраска строк те же, что в Excel-своде, но
        цветами палитры программы.

        > Название по умолчанию — «Трудоемкость (ГГГГ-ММ-ДД_ЧЧ-ММ)»; занятое имя получает номер,
        > прошлая коллекция не затирается. Остановка посреди прогона убирает недособранную
        > коллекцию целиком.

        **Журнал**

        В окне ведется журнал: какие файлы **не открылись** (повреждены, заблокированы, нет
        прав), какие **пропущены** (нет листа «Расшифровка», имя не по образцу, нет подходящих
        строк) и какие **открыты другим пользователем** — последние читаются с диска и
        помечаются, чтобы их строки не потерялись.

        > Отдельной строкой журнал считает **осиротевшие служебные файлы «~$»**: Excel
        > оставляет их после аварийного закрытия, и они приезжают вместе с копией папки.
        > Замечанием это не считается — книга не открыта, строки собраны полностью. Файлы
        > скрытые, их можно удалить.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new TimeCollectorWindow();
}
