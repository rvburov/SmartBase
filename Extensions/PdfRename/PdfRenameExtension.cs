using Avalonia.Controls;

namespace SmartBase.Extensions.PdfRename;

/// <summary>
/// Расширение «Переименование PDF»: пакетно переименовывает PDF-файлы в выбранной папке
/// по правилу «все до первого пробела + .pdf». Запускается отдельным окном
/// (<see cref="PdfRenameWindow"/>) в основном стиле приложения. Логика вынесена в
/// <see cref="PdfRenamer"/>; расширение самостоятельно и зависит только от
/// <see cref="IExtension"/> + контролов/стилей приложения.
/// </summary>
public sealed class PdfRenameExtension : IExtension
{
    public string Id   => "pdf-rename";
    public string Name => "Переименование PDF";

    public string MarkdownDescription =>
        """
        Пакетно переименовывает PDF-файлы в выбранной папке, оставляя от имени только
        обозначение документа. Нужно, когда выгрузка из архива или САПР дала имена вида
        «обозначение плюс название», а в работу требуется одно обозначение.

        ## Что делает

        Правило одно и настройки не имеет:

        - из имени файла берется все **до первого пробела**, остальное отбрасывается;
        - расширение `.pdf` сохраняется.

        Например, `XXXX.AAAAAA.BBB Кабель.pdf` станет `XXXX.AAAAAA.BBB.pdf`.

        Имена без пробела остаются как есть — менять в них нечего. Файлы других форматов
        расширение не трогает.

        ## Перед первым запуском

        Настраивать нечего: у расширения нет ни одного поля в разделе
        **Настройки → Расширения**. Достаточно папки с документами.

        ## Как пользоваться

        1. Нажмите **«Обзор»** и выберите папку с PDF-файлами.
        2. Нажмите **«Проверить»** — расширение покажет, какой файл каким станет,
           **ничего не меняя на диске**. Это предпросмотр: им и стоит начинать.
        3. Просмотрите список. Файлы, которые переименовать нельзя, помечены причиной.
        4. Нажмите **«Запустить»** и подтвердите переименование в появившемся вопросе.
        5. Долгий прогон видно на полосе; прервать его можно кнопкой «Остановить».

        ## Что получится

        Файлы в **той же папке** под новыми именами. Ничего не создается и не копируется:
        это единственное расширение, которое по своему назначению меняет исходные документы
        на диске — потому запуск и требует подтверждения.

        Отчета расширение не пишет: результат виден в самой папке, а список сделанного
        остается в журнале окна до его закрытия.

        ## Особенности

        - **Файлы не удаляются** — только переименовываются.
        - **Конфликты пропускаются, а не перезаписываются.** Конфликт бывает двух видов:
          имя уже занято другим файлом на диске либо у нескольких файлов пачки получается
          одно и то же имя. Такие файлы остаются под старыми именами, а причина видна в
          журнале окна — потерять документ при переименовании нельзя.
        - **Остановка не откатывает сделанное.** Уже переименованные файлы остаются с новыми
          именами; повторный прогон по той же папке просто доделает остальные.
        - Расширение рассчитано на десятки тысяч файлов: окно остается отзывчивым, а в журнал
          на реальном прогоне пишутся только конфликты и ошибки — успехи идут в счетчик.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new PdfRenameWindow();
}
