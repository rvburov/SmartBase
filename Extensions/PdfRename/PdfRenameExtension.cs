using Avalonia.Controls;

namespace DataBase.Extensions.PdfRename;

/// <summary>
/// Расширение «Переименование PDF»: пакетно переименовывает PDF-файлы в выбранной папке
/// по правилу «всё до первого пробела + .pdf». Запускается отдельным окном
/// (<see cref="PdfRenameWindow"/>) в основном стиле приложения. Логика вынесена в
/// <see cref="PdfRenamer"/>; расширение самостоятельно и зависит только от
/// <see cref="IExtension"/> + контролов/стилей приложения.
/// </summary>
public sealed class PdfRenameExtension : IExtension
{
    public string Id   => "pdf-rename";
    public string Name => "Переименование PDF";

    public string MarkdownDescription =>
        """
        Пакетно переименовывает PDF-файлы в выбранной папке по простому правилу.

        **Правило**
        - Из имени файла берётся всё до первого пробела, остальное отбрасывается.
        - Расширение `.pdf` сохраняется.

        Например: XXXX.AAAAAA.BBB Кабель.pdf → XXXX.AAAAAA.BBB.pdf.

        **Как пользоваться**
        1. Выберите папку с PDF-файлами.
        2. Нажмите «Проверить» — предпросмотр без изменений на диске.
        3. Нажмите «Запустить» и подтвердите переименование.

        **Безопасность**
        - Файлы не удаляются — только переименовываются.
        - Кнопка «Проверить» показывает изменения, ничего не меняя на диске.
        - Конфликты (имя занято или у нескольких файлов совпадает результат) пропускаются.
        - Реальный запуск требует подтверждения, а долгую операцию можно остановить.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new PdfRenameWindow();
}
