using Avalonia.Controls;

namespace SmartBase.Extensions.PdfRename;

/// <summary>
/// Расширение «Переименование PDF» — отдельный плагин (своя сборка, OCR и модели в своей
/// папке; см. docs/developer/features/extensions/pdf-rename.md). Два режима: по содержимому
/// скана (шаблоны с цветными рамками, Tesseract и PaddleOCR) и прежний — по имени файла.
/// Окно — <see cref="PdfRenameWindow"/>; логика — Rename/OcrRenameRun.cs и
/// <see cref="PdfRenamer"/>.
/// </summary>
public sealed class PdfRenameExtension : IExtension
{
    public const string ExtensionId = "pdf-rename";

    public string Id   => ExtensionId;
    public string Name => "Переименование PDF";

    public string MarkdownDescription =>
        """
        Пакетно переименовывает сканы конструкторской документации по их **содержимому**:
        находит на листе десятичное обозначение и наименование изделия и дает файлу имя
        `Обозначение Наименование.pdf` — в той же папке, без копий и без изменения PDF.
        Второй режим — прежний: имя по правилу «все до первого пробела».

        ## Перед первым запуском

        Расширение устанавливается отдельно: **Настройки → Расширения → Установить из файла…**
        (архив расширения для вашей ОС). Распознавание идет на этом компьютере, сканы никуда
        не отправляются, интернет не нужен.

        На Linux нужен системный Tesseract: `sudo apt install tesseract-ocr tesseract-ocr-rus`.

        ## Шаблоны

        Соберите папку образцов: по одному PDF на каждый вид бланка. **Имя файла — тип
        документа**: `Спецификация.pdf`, `Чертеж.pdf`. На образце обведите графы рамками:

        - **синяя** — обозначение;
        - **зеленая** — наименование;
        - **красно-оранжевая** — обозначение и наименование в одной области.

        Нужны либо синяя и зеленая, либо одна красно-оранжевая. Обводите **всю графу**, а не
        текст образца, и не перекрывайте буквы линией рамки. Рамку можно нарисовать в
        редакторе PDF или на картинке скана — оттенок не важен, важен цвет.

        ## Как пользоваться

        1. Выберите режим **«По содержимому»**.
        2. Укажите папку шаблонов и папку с PDF; при необходимости — **«Искать в подпапках»**.
        3. Нажмите **«Запустить»**. Ход и итог — в журнале и счетчиках; прервать —
           **«Стоп»**.

        ## Что получится

        Переименовываются только уверенно распознанные файлы: оба движка (Tesseract и
        PaddleOCR) должны прочитать одно и то же, обозначение — пройти проверку формата.
        Остальные **пропускаются без изменений**, причина — в журнале: не подошел шаблон,
        подошли несколько, движки прочитали по-разному, имя занято и т. п.

        ## Особенности

        - **Ничего не перезаписывается и не удаляется**; конфликт имени — пропуск.
        - **Многостраничные PDF**: просматриваются первые 10 страниц; все страницы, подошедшие
          к шаблонам, должны дать одни и те же данные.
        - **Остановка** не откатывает сделанное: переименованные остаются, остальные —
          как были.
        - Шаблоны читаются заново при каждом запуске; папка шаблонов внутри папки с PDF
          не обрабатывается.
        """;

    /// <summary>Запускаемое расширение — кнопка «Запустить» активна.</summary>
    public bool CanRun => true;

    public Window? CreateWindow() => new PdfRenameWindow();
}
